        Energy conserved:
            \(energyConserved)
        
        Stable shell:
            \(stableShell)
        
        Natural frequency:
            \(naturalFrequencyHz) Hz
        
        Resonance persistent:
            \(resonancePersistent)
        
        Coherence:
            \(collectiveCoherence)
        
        Energy match:
            \(energyMatch)
        
        Candidate mode:
            \(candidate)
        
        """)

        return candidate
    }
    private func isWithinHiggsEnergyWindow(
        resonantEnergy: Double
    ) -> Bool {

        let referenceEnergy =
            QRTLConstants.higgsReferenceEnergyJ

        guard referenceEnergy > 0.0,
              resonantEnergy > 0.0 else {
            return false
        }

        let relativeDifference =
            abs(
                resonantEnergy -
                referenceEnergy
            ) /
            referenceEnergy

        return relativeDifference <=
            QRTLConstants.higgsEnergyTolerance
    }
    private func evaluateStableEnergyShell() -> Bool {

        let currentEnergy =
            totalMechanicalLatticeEnergy()

        guard currentEnergy.isFinite,
              currentEnergy > 0.0 else {
            return false
        }

        if previousLatticeEnergy <= 0.0 {

            previousLatticeEnergy =
                currentEnergy

            return false
        }

        let energyChange =
            abs(
                currentEnergy -
                previousLatticeEnergy
            )

        let relativeChange =
            energyChange /
            max(
                currentEnergy,
                1.0e-30
            )

        previousLatticeEnergy =
            currentEnergy

        let tolerance =
            QRTLConstants.stableEnergyTolerance

        return relativeChange <
            tolerance
    }
