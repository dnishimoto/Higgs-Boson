    private func initializeCollision(
        kineticEnergyJ: Double,
        collisionPosition: Int
    ) {
        // --------------------------------------------------------
        // RESET COLLISION STATE
        // --------------------------------------------------------

        collisionActive = true
        collisionCompleted = false

        collectiveSignal.removeAll(keepingCapacity: true)

        naturalAngularFrequency = 0.0
        naturalFrequencyHz = 0.0

        resonantModeAmplitude = 0.0
        resonantModeEnergy = 0.0

        higgsLikeModeDetected = false
        resonancePersistence = 0.0

        // --------------------------------------------------------
        // STORE COLLISION ENERGY
        // --------------------------------------------------------

        collisionKineticEnergyJ = max(kineticEnergyJ, 0.0)

        // --------------------------------------------------------
        // CLEAR PREVIOUS LATTICE MOTION
        // --------------------------------------------------------

        for index in cells.indices {

            // Fixed lattice position is NOT changed.
            // position is a let constant in QRTLCell.

            cells[index].displacement = .zero
            cells[index].velocity = .zero

            cells[index].twist = 0.0
            cells[index].phase = 0.0
            cells[index].amplitude = 0.0

            cells[index].localEnergy = 0.0
            cells[index].localStrain = 0.0
            cells[index].couplingState = 0.0

            cells[index].modeCoordinate = 0.0
            cells[index].modeVelocity = 0.0
            cells[index].modeAcceleration = 0.0
            cells[index].modeDirection = .zero

            cells[index].previousPhase = 0.0
            cells[index].unwrappedPhase = 0.0

            cells[index].borlagrinoFlow = .zero
            cells[index].charge = 0.0
        }

        // --------------------------------------------------------
        // VALIDATE LATTICE
        // --------------------------------------------------------

        guard !cells.isEmpty else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // COLLISION LOCATION
        // --------------------------------------------------------

        let centerIndex = min(
            max(collisionPosition, 0),
            cells.count - 1
        )

        // --------------------------------------------------------
        // LOCALIZE COLLISION ENERGY
        // --------------------------------------------------------

        let radius = max(
            QRTLConstants.collisionRadius,
            1.0
        )

        var totalWeight = 0.0

        var weights = [Double](
            repeating: 0.0,
            count: cells.count
        )

        let centerX = Double(
            cells[centerIndex].position.x
        )

        let centerY = Double(
            cells[centerIndex].position.y
        )

        for index in cells.indices {

            let dx =
                Double(cells[index].position.x) - centerX

            let dy =
                Double(cells[index].position.y) - centerY

            let distanceSquared =
                dx * dx + dy * dy

            let weight = exp(
                -distanceSquared /
                (2.0 * radius * radius)
            )

            weights[index] = weight
            totalWeight += weight
        }

        guard totalWeight > 0.0 else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // CONVERT COLLISION ENERGY INTO LATTICE DISPLACEMENT
        //
        // E = 1/2 k x²
        //
        // x = sqrt(2E/k)
        // --------------------------------------------------------

        let stiffness = max(
            QRTLConstants.effectiveStiffnessNPerM,
            Double.leastNonzeroMagnitude
        )

        for index in cells.indices {

            let normalizedWeight =
                weights[index] / totalWeight

            let localEnergy =
                collisionKineticEnergyJ * normalizedWeight

            cells[index].localEnergy =
                localEnergy

            let displacementMagnitude =
                sqrt(
                    max(
                        2.0 * localEnergy / stiffness,
                        0.0
                    )
                )

            // Radial collision disturbance.
            let direction: Double =
                index == centerIndex ? 1.0 : 0.5

            let displacement =
                displacementMagnitude * direction

            // Dynamic displacement.
            cells[index].displacement.x =
                Float(displacement)

            // Store amplitude consistently with displacement.
            cells[index].amplitude =
                displacement

            // Local strain.
            cells[index].localStrain =
                displacement /
                max(
                    QRTLConstants.cellSpacing,
                    Double.leastNonzeroMagnitude
                )
        }

        // --------------------------------------------------------
        // INITIAL COLLISION SIGNAL
        // --------------------------------------------------------

        let initialSignal =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        collectiveSignal.append(
            initialSignal
        )

        // --------------------------------------------------------
        // INITIAL MECHANICAL REFERENCE
        //
        // This does not assign the collision wavelength.
        // The propagated collective signal is analyzed later.
        // --------------------------------------------------------

        let mass = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        naturalAngularFrequency =
            sqrt(stiffness / mass)

        naturalFrequencyHz =
            naturalAngularFrequency /
            (2.0 * Double.pi)

        // --------------------------------------------------------
        // DEBUG VALUES
        // --------------------------------------------------------

        let initializedEnergy =
            cells.reduce(0.0) { total, cell in
                total + cell.localEnergy
            }

        let initializedDisplacement =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        let centerCell =
            cells[centerIndex]

        /*
        print("""
        
        ========================================================
        COLLISION INITIALIZATION DEBUG
        ========================================================

        Collision kinetic energy:
            \(collisionKineticEnergyJ) J

        Localized lattice energy:
            \(initializedEnergy) J

        Energy ratio:
            \(collisionKineticEnergyJ > 0.0
                ? initializedEnergy / collisionKineticEnergyJ
                : 0.0)

        Total displacement:
            \(initializedDisplacement)

        Initial signal:
            \(initialSignal)

        Center cell:
            \(centerIndex)

        Center displacement:
            \(centerCell.displacement)

        Center local energy:
            \(centerCell.localEnergy)

        Center strain:
            \(centerCell.localStrain)

        Natural angular frequency:
            \(naturalAngularFrequency)

        Natural frequency:
            \(naturalFrequencyHz) Hz

        ========================================================
        """)
         */
        
        evaluateHelium2Candidate()
    }

    private func updateQuarkCollisionState(dt: Double) {
        guard collisionOccurred else { return }
        let progress = min(1, collisionElapsedTime / quarkVisualDuration)
        if progress < 1 {
            let compression = sin(progress * .pi * 0.5)
            for i in protonAQuarks.indices {
                protonAQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonAQuarks[i].position.x
                protonAQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            for i in protonBQuarks.indices {
                protonBQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonBQuarks[i].position.x
                protonBQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            return
        }
        let repulsionProgress = min(1, (collisionElapsedTime - quarkVisualDuration) / quarkVisualDuration)
        let repulsion = sin(repulsionProgress * .pi * 0.5)
        for i in protonAQuarks.indices {
            let o = protonAQuarks[i].originalPosition
            protonAQuarks[i].position.x = o.x - repulsion * 1.5
            protonAQuarks[i].velocity.x = -repulsion
        }
        for i in protonBQuarks.indices {
            let o = protonBQuarks[i].originalPosition
            protonBQuarks[i].position.x = o.x + repulsion * 1.5
            protonBQuarks[i].velocity.x = repulsion
        }
        if repulsionProgress >= 1 { quarksSeparated = true }
    }

    private func applyQuarkCompression(compression: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = compression * influence
            cells[i].localStrain = min(1, cells[i].localStrain + f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.05)
            cells[i].twist += f * QRTLConstants.twistAttractStrength
        }
        // Shell tracks full collision budget; instability follows compression
        energyState.shellInstability = max(energyState.shellInstability, compression)
        energyState.shellEnergy = QRTLConstants.collisionKineticEnergyJ
    }

    private func applyQuarkRepulsion(repulsion: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = repulsion * influence
            cells[i].localStrain = max(0, cells[i].localStrain - f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.1)
            cells[i].twist -= f * QRTLConstants.twistRepelStrength
        }
    }


    private func applyTwistAttractionRepulsion(
        compression: Double,
        repulsion: Double
    ) {

        let centerX =
            (protonAX + protonBX) * 0.5

        guard centerX.isFinite,
              collisionCoreRadius.isFinite,
              collisionCoreRadius > 0.0 else {
            return
        }

        for i in cells.indices {

            let cellX =
                Double(cells[i].position.x)

            guard cellX.isFinite else {
                continue
            }

            let dx =
                abs(cellX - centerX)

            guard dx <= collisionCoreRadius else {
                continue
            }

            let influence =
                max(
                    0.0,
                    1.0 - dx / collisionCoreRadius
                )

            let attract =
                compression *
                influence *
                QRTLConstants.twistAttractStrength

            let repel =
                repulsion *
                influence *
                QRTLConstants.twistRepelStrength

            let twistDelta =
                attract - repel

            guard twistDelta.isFinite else {
                continue
            }

            // Twist is a dimensionless QRTL state.
            // It does NOT directly inject velocity or energy.
            cells[i].twist += twistDelta

            if !cells[i].twist.isFinite {
                cells[i].twist = 0.0
            }
        }
    }


    private func releaseCollisionEnergy(amount: Double) {
        guard !cells.isEmpty else { return }
        let release = collisionCoreEnergyJ * amount * 0.001
        collisionReleasedEnergyJ += release
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            let influence = exp(-(dx * dx) / (collisionCoreRadius * collisionCoreRadius))
            cells[i].amplitude = min(1, cells[i].amplitude + influence * amount * 0.02)
        }
    }

    private func restoreCollisionSymmetry() {
        energyState.shellInstability = 0
        energyState.isUnstable = false
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        collisionEnergySymmetry = 1
        collisionMassEnergyJ = 0
        collisionMassEquivalentKg = 0
        collisionCoreEnergyJ = 0
    }

    private func updateShellState(dt: Double) {
        guard energyState.isUnstable else { return }
        let rate = dt / shellRelaxationVisualSeconds
        energyState.shellInstability = max(0, energyState.shellInstability - rate)
        energyState.deformation = energyState.shellInstability
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        if energyState.shellInstability < 0.05 {
            energyState.isUnstable = false
        }
        let s = Float(1 + energyState.shellInstability * 0.9)
        protonAShellNode.scale = SCNVector3(s, s, s)
        protonBShellNode.scale = SCNVector3(s, s, s)
    }

    private func updateEnergyShell() {

        guard collisionKineticEnergyJ.isFinite,
              collisionKineticEnergyJ > 0.0,
              shellActive else {
            return
        }
        
        print("""
         🔥🔥🔥 updateEnergyShell CALLED
         collisionKineticEnergyJ = \(collisionKineticEnergyJ)
         shellActive = \(shellActive)
         shellFormationTime = \(shellFormationTime)
         shellEnergyReleased = \(shellEnergyReleased)
         shellStoredEnergyJ = \(shellStoredEnergyJ)
         cells = \(cells.count)
         """)

        let physicsDt = QRTLConstants.timeStep

        guard physicsDt.isFinite,
              physicsDt > 0.0 else {
            return
        }

        // ============================================================
        // SHELL FORMATION
        // ============================================================

        if shellFormationTime <= 0.0 {

            shellPhase = .forming
            shellEnergyReleased = false

            // Store the incoming collision energy in the shell.
            shellStoredEnergyJ = collisionKineticEnergyJ

            print("""
            ============================================================
            QRTL ENERGY SHELL FORMED
            ============================================================
            Collision energy:
                \(collisionKineticEnergyJ) J

            Shell stored energy:
                \(shellStoredEnergyJ) J
            ============================================================
            """)
        }

        // ============================================================
        // ADVANCE PHYSICAL SHELL TIME
        // ============================================================

        shellFormationTime += physicsDt

        let formationDuration = max(
            QRTLConstants.timeStep * 5.0,
            1.0e-3
        )

        // ============================================================
        // SHELL FORMING
        // ============================================================

        if shellFormationTime < formationDuration {

            shellPhase = .forming
            shellEnergyReleased = false

            return
        }

        // ============================================================
        // SHELL COMPRESSED / STORED ENERGY
        // ============================================================

        if shellFormationTime < formationDuration * 2.0 {

            shellPhase = .compressed
            shellEnergyReleased = false

            return
        }

        // ============================================================
        // PREVENT DOUBLE RELEASE
        // ============================================================

        guard !shellEnergyReleased else {

            shellPhase = .released

            return
        }

        // ============================================================
        // ENERGY AVAILABLE FOR RELEASE
        // ============================================================

        let releasedEnergyJ = shellStoredEnergyJ

        guard releasedEnergyJ.isFinite,
              releasedEnergyJ > 0.0 else {
            return
        }

        // ============================================================
        // FIND COLLISION-ACTIVE CELLS
        // ============================================================

        let activeIndices = cells.indices.filter {
            cells[$0].localEnergy >
                QRTLConstants.activeEnergyThreshold
        }

        guard !activeIndices.isEmpty else {

            print("""
            ============================================================
            ⚠️ SHELL RELEASE BLOCKED
            ============================================================
            No active lattice cells available.

            Shell energy:
                \(releasedEnergyJ) J
            ============================================================
            """)

            return
        }

        // ============================================================
        // ENERGY PER ACTIVE CELL
        // ============================================================

        let energyPerCell =
            releasedEnergyJ /
            Double(activeIndices.count)

        guard energyPerCell.isFinite,
              energyPerCell > 0.0 else {
            return
        }

        // ============================================================
        // EFFECTIVE CELL MASS
        // ============================================================

        let cellMassKg = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        // ============================================================
        // SHELL ENERGY → KINETIC VELOCITY
        //
        // E = 1/2 m v²
        //
        // v = sqrt(2E/m)
        // ============================================================

        let velocityMagnitude = sqrt(
            2.0 *
            energyPerCell /
            cellMassKg
        )

        guard velocityMagnitude.isFinite,
              velocityMagnitude > 0.0 else {
            return
        }

        // ============================================================
        // DISTRIBUTE SHELL ENERGY INTO LATTICE MOTION
        // ============================================================

        var injectedKineticEnergyJ = 0.0

        for index in activeIndices {

            // --------------------------------------------------------
            // MODE DIRECTION
            // --------------------------------------------------------

            let direction = SIMD3<Double>(
                Double(cells[index].modeDirection.x),
                Double(cells[index].modeDirection.y),
                Double(cells[index].modeDirection.z)
            )

            let directionLength = simd_length(direction)

            let normalizedDirection =
                directionLength > 0.0
                ? direction / directionLength
                : SIMD3<Double>(1.0, 0.0, 0.0)

            // --------------------------------------------------------
            // INJECT VELOCITY
            // --------------------------------------------------------

            let velocity =
                normalizedDirection *
                velocityMagnitude

            cells[index].velocity =
                SIMD3<Float>(
                    Float(velocity.x),
                    Float(velocity.y),
                    Float(velocity.z)
                )

            // --------------------------------------------------------
            // UPDATE MODE STATE
            // --------------------------------------------------------

            let displacement = SIMD3<Double>(
                Double(cells[index].displacement.x),
                Double(cells[index].displacement.y),
                Double(cells[index].displacement.z)
            )

            let modeCoordinate =
                simd_dot(
                    displacement,
                    normalizedDirection
                )

            let modeVelocity =
                simd_dot(
                    velocity,
                    normalizedDirection
                )

            let omega = sqrt(
                QRTLConstants.effectiveStiffnessNPerM /
                cellMassKg
            )

            guard omega.isFinite,
                  omega > 0.0 else {
                continue
            }

            cells[index].modeCoordinate =
                modeCoordinate

            cells[index].modeVelocity =
                modeVelocity

            cells[index].modeAcceleration =
                -omega * omega * modeCoordinate

            // --------------------------------------------------------
            // PHASE
            // --------------------------------------------------------

            cells[index].previousPhase =
                cells[index].phase

            cells[index].phase =
                atan2(
                    modeVelocity,
                    omega * modeCoordinate
                )

            // --------------------------------------------------------
            // AMPLITUDE
            // --------------------------------------------------------

            let amplitudeSquared =
                modeCoordinate * modeCoordinate +
                pow(modeVelocity / omega, 2.0)

            cells[index].amplitude =
                sqrt(
                    max(
                        0.0,
                        amplitudeSquared
                    )
                )

            // --------------------------------------------------------
            // MECHANICAL ENERGY
            // --------------------------------------------------------

            let potentialEnergy =
                0.5 *
                QRTLConstants.effectiveStiffnessNPerM *
                simd_length_squared(displacement)

            let kineticEnergy =
                0.5 *
                cellMassKg *
                simd_length_squared(velocity)

            let totalCellEnergy =
                potentialEnergy +
                kineticEnergy

            cells[index].localEnergy =
                max(
                    0.0,
                    totalCellEnergy
                )

            injectedKineticEnergyJ +=
                kineticEnergy
        }

        // ============================================================
        // VERIFY ENERGY TRANSFER
        // ============================================================

        let transferErrorJ =
            injectedKineticEnergyJ -
            releasedEnergyJ

        let transferErrorFraction =
            releasedEnergyJ > 0.0
            ? abs(transferErrorJ) / releasedEnergyJ
            : 0.0

        // ============================================================
        // TRANSFER OWNERSHIP
        // ============================================================

        shellEnergyReleased = true
        shellPhase = .released

        // Shell no longer owns the released energy.
        shellStoredEnergyJ = 0.0

        // ============================================================
        // RELEASE DIAGNOSTICS
        // ============================================================

        print("""
        ============================================================
        QRTL SHELL → LATTICE KINETIC ENERGY TRANSFER
        ============================================================

        Released shell energy:
            \(releasedEnergyJ) J

        Active lattice cells:
            \(activeIndices.count)

        Energy per cell:
            \(energyPerCell) J

        Effective cell mass:
            \(cellMassKg) kg

        Injected velocity:
            \(velocityMagnitude) m/s

        Measured kinetic energy:
            \(injectedKineticEnergyJ) J

        Energy transfer error:
            \(transferErrorJ) J

        Relative transfer error:
            \(transferErrorFraction)

        Shell energy remaining:
            \(shellStoredEnergyJ) J

        Shell released:
            \(shellEnergyReleased)

        Shell phase:
            \(shellPhase)

        ============================================================
        """)
    }
    private func injectShellEnergyIntoLattice(energyJ: Double) {

        guard energyJ.isFinite,
              energyJ > 0.0,
              !cells.isEmpty else {
            return
        }

        let mass = QRTLConstants.effectiveMassKg

        guard mass.isFinite,
              mass > 0.0 else {
            return
        }

        // ============================================================
        // COLLISION CENTER
        // ============================================================

        let center = SIMD3<Double>(
            0.0,
            0.0,
            0.0
        )

        let radius = max(
            1.0,
            QRTLConstants.pumpRadius
        )

        var weights: [(index: Int, weight: Double)] = []

        // ============================================================
        // LOCALIZED GAUSSIAN PROFILE
        // ============================================================

        for index in cells.indices {

            let cell = cells[index]

            let x = Double(cell.position.x)
            let y = Double(cell.position.y)
            let z = Double(cell.position.z)

            let dx = x - center.x
            let dy = y - center.y
            let dz = z - center.z

            let distanceSquared =
                dx * dx +
                dy * dy +
                dz * dz

            let weight = exp(
                -distanceSquared /
                (2.0 * radius * radius)
            )

            if weight > 1.0e-12 {
                weights.append(
                    (
                        index: index,
                        weight: weight
                    )
                )
            }
        }

        guard !weights.isEmpty else {
            return
        }

        // ============================================================
        // EXACT KINETIC-ENERGY NORMALIZATION
        //
        // E = 1/2 m Σv²
        // ============================================================

        let weightSquaredSum =
            weights.reduce(0.0) {
                $0 + ($1.weight * $1.weight)
            }

        guard weightSquaredSum.isFinite,
              weightSquaredSum > 0.0 else {
            return
        }

        let velocityScale = sqrt(
            2.0 * energyJ /
            (mass * weightSquaredSum)
        )

        guard velocityScale.isFinite else {
            return
        }

        // ============================================================
        // APPLY RADIAL IMPULSE
        // ============================================================

        for item in weights {

            let cell = cells[item.index]

            let x = Double(cell.position.x)
            let y = Double(cell.position.y)
            let z = Double(cell.position.z)

            let dx = center.x - x
            let dy = center.y - y
            let dz = center.z - z

            let distanceSquared =
                dx * dx +
                dy * dy +
                dz * dz

            // Center cell has no defined radial direction.
            guard distanceSquared > 1.0e-20 else {
                continue
            }

            let distance = sqrt(distanceSquared)

            let direction = SIMD3<Float>(
                Float(dx / distance),
                Float(dy / distance),
                Float(dz / distance)
            )

            let velocityMagnitude =
                Float(
                    velocityScale * item.weight
                )

            guard velocityMagnitude.isFinite else {
                continue
            }

            cells[item.index].velocity +=
                direction * velocityMagnitude
        }
    }
    private func releaseShellEnergyIntoLattice() {

        guard !shellEnergyReleased else {
            return
        }

        guard shellStoredEnergyJ.isFinite,
              shellStoredEnergyJ > 0.0 else {
            return
        }

        // ============================================================
        // ENERGY LEAVING THE SHELL
        // ============================================================

        let energyToRelease =
            shellStoredEnergyJ *
            QRTLConstants.shellLatticeTransferFraction

        guard energyToRelease.isFinite,
              energyToRelease > 0.0 else {
            return
        }

        // ============================================================
        // SHELL → LATTICE
        // ============================================================

        injectShellEnergyIntoLattice(
            energyJ: energyToRelease
        )

        // ============================================================
        // ENERGY CONSERVATION
        // ============================================================

        shellStoredEnergyJ -= energyToRelease

        shellStoredEnergyJ = max(
            0.0,
            shellStoredEnergyJ
        )

        shellEnergyReleased = true
        shellActive = false
        shellPhase = .released
    }
    private func physicalEnergy(
        displacement: SIMD3<Float>,
        velocity: SIMD3<Float>
    ) -> Double {

        let spacing =
            QRTLConstants.latticeCellSpacingMeters

        let mass =
            QRTLConstants.effectiveMassKg

        let stiffness =
            QRTLConstants.effectiveStiffnessNPerM

        guard spacing.isFinite,
              spacing > 0.0,
              mass.isFinite,
              mass > 0.0,
              stiffness.isFinite,
              stiffness > 0.0,
              displacement.x.isFinite,
              displacement.y.isFinite,
              displacement.z.isFinite,
              velocity.x.isFinite,
              velocity.y.isFinite,
              velocity.z.isFinite else {
            return 0.0
        }

        let d2 =
            Double(displacement.x) * Double(displacement.x) +
            Double(displacement.y) * Double(displacement.y) +
            Double(displacement.z) * Double(displacement.z)

        let v2 =
            Double(velocity.x) * Double(velocity.x) +
            Double(velocity.y) * Double(velocity.y) +
            Double(velocity.z) * Double(velocity.z)

        guard d2.isFinite, d2 >= 0.0,
              v2.isFinite, v2 >= 0.0 else {
            return 0.0
        }

        // Convert lattice units → SI units exactly once.
        let xPhysical = Foundation.sqrt(d2) * spacing
        let vPhysical = Foundation.sqrt(v2) * spacing

        let potential =
            0.5 *
            stiffness *
            xPhysical *
            xPhysical

        let kinetic =
            0.5 *
            mass *
            vPhysical *
            vPhysical

        let total =
            potential + kinetic

        guard total.isFinite,
              total >= 0.0 else {
            return 0.0
        }

        return total
    }

    func totalMechanicalLatticeEnergy() -> Double {
        cells.reduce(0.0) { $0 + physicalEnergy(displacement: $1.displacement, velocity: $1.velocity) }
    }


    private func updateLattice(dt: Double) {

        guard !cells.isEmpty else {
            return
        }

        print(
            "LATTICE STEP:",
            "collisionActive =", collisionActive,
            "collisionImpulseApplied =", collisionImpulseApplied,
            "cells =", cells.count
        )

        // ============================================================
        // PHYSICAL LATTICE TIMESTEP
        // ============================================================

        let physicsDt = QRTLConstants.timeStep

        guard physicsDt > 0.0,
              physicsDt.isFinite else {
            return
        }

        // ============================================================
        // COLLISION STATE
        // ============================================================

        guard collisionActive else {
            return
        }

        // ============================================================
        // COLLISION ENERGY
        // ============================================================

        guard collisionKineticEnergyJ.isFinite,
              collisionKineticEnergyJ > 0.0 else {
            return
        }

        // ============================================================
        // ONE-TIME COLLISION ENERGY DEPOSITION
        // ============================================================

        if !collisionImpulseApplied {

            let collisionEnergy =
                collisionKineticEnergyJ

            let excitationEnergy =
                collisionEnergy *
                QRTLConstants.collisionKineticFractionToPotential

            let stiffness =
                QRTLConstants.effectiveStiffnessNPerM

            let spacing =
                QRTLConstants.latticeCellSpacingMeters

            guard excitationEnergy.isFinite,
                  excitationEnergy > 0.0,
                  stiffness.isFinite,
                  stiffness > 0.0,
                  spacing.isFinite,
                  spacing > 0.0 else {
                return
            }

            let centerIndex =
                cells.count / 2

            let centerPosition =
                cells[centerIndex].position

            let radius =
                QRTLConstants.collisionRadius

            guard radius.isFinite,
                  radius > 0.0 else {
                return
            }

            var weights =
                Array(
                    repeating: 0.0,
                    count: cells.count
                )

            var totalWeight = 0.0

            // --------------------------------------------------------
            // COLLISION WEIGHTS
            // --------------------------------------------------------

            for index in cells.indices {

                let p =
                    cells[index].position

                let dx =
                    Double(p.x - centerPosition.x)

                let dy =
                    Double(p.y - centerPosition.y)

                let dz =
                    Double(p.z - centerPosition.z)

                let distance =
                    Foundation.sqrt(
                        dx * dx +
                        dy * dy +
                        dz * dz
                    )

                guard distance.isFinite,
                      distance <= radius else {
                    continue
                }

                let normalized =
                    distance / radius

                let weight =
                    max(
                        0.0,
                        1.0 - normalized
                    )

                weights[index] =
                    weight

                totalWeight +=
                    weight
            }

            guard totalWeight.isFinite,
                  totalWeight > 0.0 else {
                return
            }

            // --------------------------------------------------------
            // ENERGY-CORRECT LATTICE DISPLACEMENT
            //
            // Stored displacement = lattice units.
            //
            // Physical displacement:
            //
            // xPhysical =
            //     displacement * latticeCellSpacingMeters
            //
            // E = 1/2 k x²
            // --------------------------------------------------------

            let baseDisplacement =
                Foundation.sqrt(
                    excitationEnergy /
                    (
                        0.5 *
                        stiffness *
                        spacing *
                        spacing *
                        totalWeight
                    )
                )

            guard baseDisplacement.isFinite else {
                return
            }

            // --------------------------------------------------------
            // APPLY COLLISION COMPRESSION
            // --------------------------------------------------------

            var actualDepositedEnergy =
                0.0

            var affectedCellCount =
                0

            for index in cells.indices {

                let weight =
                    weights[index]

                guard weight > 0.0 else {
                    continue
                }

                let displacementMagnitude =
                    baseDisplacement *
                    Foundation.sqrt(weight)

                guard displacementMagnitude.isFinite else {
                    continue
                }

                let p =
                    cells[index].position

                let directionVector =
                    SIMD3<Float>(
                        Float(p.x - centerPosition.x),
                        Float(p.y - centerPosition.y),
                        Float(p.z - centerPosition.z)
                    )

                let length =
                    simd_length(directionVector)

                let direction: SIMD3<Float>

                if length > 0.0 {
                    direction =
                        directionVector / length
                } else {
                    direction =
                        SIMD3<Float>(0, 0, 1)
                }

                let boundedDisplacement =
                    min(
                        displacementMagnitude,
                        QRTLConstants.maxLatticeDisplacement
                    )

                cells[index].displacement =
                    direction *
                    Float(boundedDisplacement)

                // Collision deposition initially contains potential
                // energy only. Velocity starts at zero.
                cells[index].velocity =
                    SIMD3<Float>(0, 0, 0)

                let energy =
                    physicalEnergy(
                        displacement:
                            cells[index].displacement,
                        velocity:
                            cells[index].velocity
                    )

                if energy.isFinite,
                   energy >= 0.0 {

                    cells[index].localEnergy =
                        energy

                    actualDepositedEnergy +=
                        energy

                } else {

                    cells[index].localEnergy =
                        0.0
                }

                affectedCellCount +=
                    1
            }

            depositedEnergyJ =
                actualDepositedEnergy

            initialAffectedCellCount =
                affectedCellCount

            collisionImpulseApplied =
                true

            print("""
            ============================================================
            COLLISION ENERGY DEPOSITION
            ============================================================
            Collision kinetic energy:
                \(collisionEnergy) J

            Excitation energy:
                \(excitationEnergy) J

            Deposited lattice energy:
                \(actualDepositedEnergy) J

            Affected cells:
                \(affectedCellCount)

            Base displacement:
                \(baseDisplacement) lattice units

            Physical base displacement:
                \(baseDisplacement * spacing) m
            ============================================================
            """)
        }

        // ============================================================
        // LATTICE UPDATE
        // ============================================================

        for index in cells.indices {

            var cell =
                cells[index]

            // --------------------------------------------------------
            // FINITE-VALUE RECOVERY
            // --------------------------------------------------------

            if !cell.displacement.x.isFinite ||
               !cell.displacement.y.isFinite ||
               !cell.displacement.z.isFinite {

                cell.displacement =
                    SIMD3<Float>(0, 0, 0)
            }

            if !cell.velocity.x.isFinite ||
               !cell.velocity.y.isFinite ||
               !cell.velocity.z.isFinite {

                cell.velocity =
                    SIMD3<Float>(0, 0, 0)
            }

            // ========================================================
            // NOTE ON REMOVED SECOND EVOLUTION PASS
            //
            // This loop used to independently re-evolve cell.displacement
            // and cell.velocity every frame via a semi-implicit Euler
            // integrator (F = -kx -> a -> v += a*dt -> x += v*dt),
            // explicitly treating cell.velocity as "lattice-units per
            // second" and clamping it to ±QRTLConstants.maxLatticeVelocity
            // (50.0) under that convention.
            //
            // updateCollisionDynamics() (called earlier this same frame,
            // in updatePhysics) already evolves the SAME cell.displacement
            // / cell.velocity fields via an exact analytic SHM rotation,
            // in genuine physical units (meters, m/s). Running both meant
            // the lattice was evolved twice per frame by two physics
            // models that disagreed about what the stored numbers even
            // meant — the second pass clobbered the first's physically
            // meaningful (if numerically extreme, given the current
            // stiffness constant) result with a value computed under an
            // incompatible unit assumption, destroying any genuine
            // oscillatory signal before identifyResonantMode() could ever
            // see it.
            //
            // updateCollisionDynamics() is now the single evolution
            // pathway. This block only clamps whatever it produced, in
            // the SAME physical units it actually uses, so a numerical
            // blowup (e.g. from the current astronomically large
            // effective stiffness) can't propagate into localEnergy /
            // latticeEnergy unclamped — it no longer re-derives
            // displacement or velocity from scratch.
            // ========================================================

            let velocityLimitPhysical =
                Float(QRTLConstants.maxLatticeVelocity)

            let displacementLimitPhysical =
                Float(QRTLConstants.maxLatticeDisplacement)

            cell.velocity.x =
                max(
                    -velocityLimitPhysical,
                    min(
                        velocityLimitPhysical,
                        cell.velocity.x
                    )
                )

            cell.velocity.y =
                max(
                    -velocityLimitPhysical,
                    min(
                        velocityLimitPhysical,
                        cell.velocity.y
                    )
                )

            cell.velocity.z =
                max(
                    -velocityLimitPhysical,
                    min(
                        velocityLimitPhysical,
                        cell.velocity.z
                    )
                )

            cell.displacement.x =
                max(
                    -displacementLimitPhysical,
                    min(
                        displacementLimitPhysical,
                        cell.displacement.x
                    )
                )

            cell.displacement.y =
                max(
                    -displacementLimitPhysical,
                    min(
                        displacementLimitPhysical,
                        cell.displacement.y
                    )
                )

            cell.displacement.z =
                max(
                    -displacementLimitPhysical,
                    min(
                        displacementLimitPhysical,
                        cell.displacement.z
                    )
                )

            // ========================================================
            // LOCAL PHYSICAL ENERGY
            // ========================================================

            let energy =
                physicalEnergy(
                    displacement:
                        cell.displacement,
                    velocity:
                        cell.velocity
                )

            if energy.isFinite,
               energy >= 0.0 {

                cell.localEnergy =
                    energy

            } else {

                cell.localEnergy =
                    0.0

                cell.velocity =
                    SIMD3<Float>(0, 0, 0)
            }

            // ========================================================
            // PHASE
            // ========================================================

            if !cell.phase.isFinite {
                cell.phase = 0.0
            }

            let omega =
                naturalAngularFrequency.isFinite
                ? naturalAngularFrequency
                : 0.0

            let phaseIncrementDouble =
                omega * physicsDt

            if phaseIncrementDouble.isFinite {

                cell.phase +=
                    phaseIncrementDouble
            }

            if !cell.phase.isFinite {
                cell.phase = 0.0
            }

            cell.phase =
                cell.phase.truncatingRemainder(
                    dividingBy:
                        2.0 * Double.pi
                )

            if !cell.phase.isFinite {
                cell.phase = 0.0
            }

            // ========================================================
            // AMPLITUDE
            //
            // Stored in lattice units.
            // ========================================================

            let amplitude =
                simd_length(
                    cell.displacement
                )

            cell.amplitude =
                amplitude.isFinite
                ? Double(amplitude)
                : 0.0

            // ========================================================
            // SAVE CELL
            // ========================================================

            cells[index] =
                cell
        }

        // ============================================================
        // TOTAL LATTICE ENERGY
        // ============================================================

        var totalLatticeEnergy =
            0.0

        for cell in cells {

            if cell.localEnergy.isFinite,
               cell.localEnergy >= 0.0 {

                totalLatticeEnergy +=
                    cell.localEnergy
            }
        }

        latticeEnergy =
            totalLatticeEnergy.isFinite
            ? totalLatticeEnergy
            : 0.0

        // ============================================================
        // ENERGY ACCOUNTING
        // ============================================================

        let accountedEnergy =
            latticeEnergy +
            ejectedEnergyJ

        if accountedEnergy.isFinite {

            dissipatedEnergyJ =
                max(
                    0.0,
                    collisionKineticEnergyJ -
                    accountedEnergy
                )

        } else {

            dissipatedEnergyJ =
                0.0
        }

        // ============================================================
        // ENERGY CONSERVATION DEBUG
        // ============================================================

        if latticeEnergy.isFinite,
           collisionKineticEnergyJ.isFinite,
           collisionKineticEnergyJ > 0.0 {

            let energyRatio =
                latticeEnergy /
                collisionKineticEnergyJ

            if energyRatio > 1.001 {

                print("""
                ⚠️ LATTICE ENERGY EXCEEDS COLLISION BUDGET

                Collision energy:
                    \(collisionKineticEnergyJ) J

                Lattice energy:
                    \(latticeEnergy) J

                Energy ratio:
                    \(energyRatio)

                Excess energy:
                    \(latticeEnergy - collisionKineticEnergyJ) J
                """)
            }
        }

        // ============================================================
        // COLLECTIVE SIGNAL
        // ============================================================

        let signal =
            cells.reduce(0.0) {

                partialResult,
                cell in

                guard cell.amplitude.isFinite,
                      cell.phase.isFinite else {

                    return partialResult
                }

                return partialResult +
                    cell.amplitude *
                    cos(cell.phase)
            }

        if signal.isFinite {

            collectiveSignal.append(
                signal
            )

        } else {

            collectiveSignal.append(
                0.0
            )
        }

        // ============================================================
        // BOUNDED SPECTRAL BUFFER
        // ============================================================

        let maxSamples =
            QRTLConstants.spectralSampleCount

        if collectiveSignal.count >
           maxSamples {

            collectiveSignal.removeFirst(
                collectiveSignal.count -
                maxSamples
            )
        }
    }
    /// Borlagrino flow from kinetic↔potential conversion and twist gradients.
    /// Charge from circulation; does not create energy.
    private func updateBorlagrinoAndCharge(dt: Double) {
        guard collisionOccurred, !cells.isEmpty else {
            averageBorlagrinoMagnitude = 0
            netEmergentCharge = 0
            chargeAsymmetry = 0
            return
        }
        var nextFlow = cells.map { $0.borlagrinoFlow }
        var nextCharge = cells.map { $0.charge }
        let center = SIMD3<Float>(0, 0, 0)

        for i in cells.indices {
            let cell = cells[i]
            // Conversion proxy: potential-like strain vs kinetic-like |v|
            let potProxy = cell.localStrain
            let kinProxy = min(1, Double(simd_length(cell.velocity)) / QRTLConstants.maxLatticeVelocity)
            let conversion = potProxy - kinProxy

            var twistGrad = SIMD3<Float>(0, 0, 0)
            for ni in cell.neighbors {
                let dTwist = Float(cells[ni].twist - cell.twist)
                twistGrad += (cells[ni].position - cell.position) * dTwist
            }
            if !cell.neighbors.isEmpty {
                twistGrad /= Float(cell.neighbors.count)
            }

            var flow = cell.borlagrinoFlow
            flow += twistGrad * Float(QRTLConstants.borlagrinoCoupling * conversion)
            // Circulation bias around collision axis
            let radial = cell.position - center
            let circ = SIMD3<Float>(-radial.y, radial.x, 0) * Float(conversion * 0.05)
            flow += circ
            flow *= Float(1.0 - QRTLConstants.borlagrinoDamping)
            if simd_length(flow) > 2 { flow = simd_normalize(flow) * 2 }
            nextFlow[i] = flow

            // Emergent charge ~ local circulation (finite difference curl proxy)
            var curlZ: Float = 0
            for ni in cell.neighbors {
                let f = cells[ni].borlagrinoFlow
                curlZ += f.y * (cells[ni].position.x - cell.position.x)
                    - f.x * (cells[ni].position.y - cell.position.y)
            }
            let q = Double(curlZ) * QRTLConstants.chargeFromCirculation
            nextCharge[i] = nextCharge[i] * 0.9 + q * 0.1
        }

        for i in cells.indices {
            cells[i].borlagrinoFlow = nextFlow[i]
            cells[i].charge = nextCharge[i]
        }

        let n = Double(max(cells.count, 1))
        averageBorlagrinoMagnitude = cells.reduce(0.0) {
            $0 + Double(simd_length($1.borlagrinoFlow))
        } / n
        netEmergentCharge = cells.reduce(0.0) { $0 + $1.charge }
        let absSum = cells.reduce(0.0) { $0 + abs($1.charge) }
        chargeAsymmetry = absSum > 1e-12 ? abs(netEmergentCharge) / absSum : 0
    }

    private func calculateCollectiveCoherence() {

        var real = 0.0
        var imag = 0.0
        var w = 0.0
        var activeCellCount = 0

        for c in cells {

            let weight = max(Double(c.localEnergy), 0.0)

            guard weight > QRTLConstants.activeEnergyThresholdJ else {
                continue
            }

            activeCellCount += 1

            real += weight * cos(Double(c.phase))
            imag += weight * sin(Double(c.phase))
            w += weight
        }

        let phaseVectorMagnitude =
            sqrt(real * real + imag * imag)

        guard w > 0.0 else {

            collectiveCoherence = 0.0

            print("""
            
            ===== COLLECTIVE COHERENCE DEBUG =====

            Total cells:
                \(cells.count)

            Active cells:
                \(activeCellCount)

            Active energy threshold:
                \(QRTLConstants.activeEnergyThresholdJ) J

            Real phase component:
                \(real)

            Imaginary phase component:
                \(imag)

            Phase-vector magnitude:
                \(phaseVectorMagnitude)

            Weighted active energy:
                \(w) J

            Collective coherence:
                0.0

            ⚠️ No active energy above threshold.

            Resonant mode energy:
                \(resonantModeEnergyJ) J

            =======================================

            """)

            return
        }

        // --------------------------------------------------------
        // Collective phase coherence
        // --------------------------------------------------------

        collectiveCoherence =
            min(1.0, phaseVectorMagnitude / w)

        // --------------------------------------------------------
        // IMPORTANT:
        //
        // Do NOT calculate resonantModeEnergyJ here.
        //
        // Coherence describes phase alignment.
        // The resonant-mode energy must come from the
        // identified spatial mode at the measured resonance
        // frequency.
        // --------------------------------------------------------

        resonantModeEnergyGeV =
            resonantModeEnergyJ /
            QRTLConstants.joulePerGeV

        resonantModeEnergyTeV =
            resonantModeEnergyGeV / 1_000.0

        resonantModeEnergy =
            resonantModeEnergyJ

        print("""
        
        ===== COLLECTIVE COHERENCE DEBUG =====

        Total cells:
            \(cells.count)

        Active cells:
            \(activeCellCount)

        Active energy threshold:
            \(QRTLConstants.activeEnergyThresholdJ) J

        Lattice energy:
            \(latticeEnergy) J

        Real phase component:
            \(real)

        Imaginary phase component:
            \(imag)

        Phase-vector magnitude:
            \(phaseVectorMagnitude)

        Weighted active energy:
            \(w) J

        Collective coherence:
            \(collectiveCoherence)

        Coherence squared:
            \(collectiveCoherence * collectiveCoherence)

        Resonant mode energy:
            \(resonantModeEnergyJ) J

        Resonant mode energy:
            \(resonantModeEnergyGeV) GeV

        Resonant mode energy:
            \(resonantModeEnergyTeV) TeV

        =========================================

        """)
    }
    private func normalizedCollisionDirection() -> SIMD3<Float> {

        let magnitude = simd_length(collisionDirection)

        guard magnitude > 1.0e-12 else {
            return SIMD3<Float>(1, 0, 0)
        }

        return collisionDirection / magnitude
    }
    private func recordCollectiveLatticeSignal() {

        guard collisionOccurred, !cells.isEmpty else { return }

        let axis = normalizedCollisionDirection()

        var weightedDisplacement = 0.0
        var weightedVelocity = 0.0
        var totalEnergy = 0.0

        for c in cells {

            let energy = max(Double(c.localEnergy), 0.0)

            guard energy > 1e-30 else { continue }

            let displacementProjection =
                Double(simd_dot(c.displacement, axis))

            let velocityProjection =
                Double(simd_dot(c.velocity, axis))

            weightedDisplacement +=
                energy * displacementProjection

            weightedVelocity +=
                energy * velocityProjection

            totalEnergy += energy
        }

        guard totalEnergy > 1e-30 else {
            return
        }

        let collectiveDisplacement =
            weightedDisplacement / totalEnergy

        let collectiveVelocity =
            weightedVelocity / totalEnergy

        // Collision-direction collective signal.
        // The velocity term preserves the time-varying component
        // without changing the physical energy accounting.
        let signal =
            collectiveDisplacement +
            collectiveVelocity * QRTLConstants.timeStep

        spectralAnalyzer.append(signal)

        spectralSampleCount =
            spectralAnalyzer.samples.count

        spectralNyquistHz =
            0.5 / QRTLConstants.timeStep

        if spectralAnalyzer.samples.count >=
            min(256, QRTLConstants.spectralSampleCount),
           let spectral =
                spectralAnalyzer.analyze(
                    sampleInterval: QRTLConstants.timeStep
                ) {

            resonantFrequencyHz =
                spectral.frequencyHz

            resonantAngularFrequency =
                spectral.angularFrequency

            resonantWavelengthMeters =
                spectral.wavelengthMeters

            spectralPeakAmplitude =
                spectral.peakAmplitude

            spectralAnalysisComplete = true
        }
    }

    private func measureCollectiveMode() {
        var ws = 0.0, wv = 0.0, tw = 0.0
        for c in cells {
            let weight = max(c.localEnergy, 0) + c.amplitude * c.amplitude
            guard weight > QRTLConstants.activeEnergyThresholdJ else { continue }
            ws += c.modeCoordinate * weight
            wv += c.modeVelocity * weight
            tw += weight
        }
        guard tw > 0 else { return }
        let signal = ws / tw
        let vel = wv / tw
        if !phaseReferenceEstablished {
            previousCollectiveSignal = signal
            previousCollectiveVelocity = vel
            phaseReferenceEstablished = true
            return
        }
        let cross = previousCollectiveSignal <= 0 && signal > 0 && vel > 0
        if cross {
            if let prev = lastPositiveCrossingTime {
                let period = simulationTime - prev
                if period > 1e-6, period.isFinite {
                    measuredPeriods.append(period)
                    if measuredPeriods.count > 8 { measuredPeriods.removeFirst() }
                    let avg = measuredPeriods.reduce(0, +) / Double(measuredPeriods.count)
                    if avg > 0 { resonantFrequencyHz = 1.0 / avg }
                }
            }
            lastPositiveCrossingTime = simulationTime
        }
        previousCollectiveSignal = signal
        previousCollectiveVelocity = vel
    }

    private func massFromFrequency(_ f: Double) -> Double {
        guard f.isFinite, f > 0 else { return 0 }
        return (QRTLConstants.planckConstant * f) / QRTLConstants.joulePerGeV
    }

    private func updateHiggsLikeMode(dt: Double) {
        higgsMode.age += dt
        calculateCollectiveCoherence()

        var wa = 0.0, pr = 0.0, pi = 0.0, pw = 0.0
        for c in cells {
            let w = max(c.localEnergy, 0)
            guard w > QRTLConstants.activeEnergyThresholdJ else { continue }
            wa += abs(c.modeCoordinate) * w
            pr += w * cos(c.phase)
            pi += w * sin(c.phase)
            pw += w
        }
        let amp = pw > 0 ? wa / pw : 0
        let coh = pw > 0 ? min(1, sqrt(pr * pr + pi * pi) / pw) : 0

        resonantMassGeV = massFromFrequency(resonantFrequencyHz)
        massDistanceFromTarget = abs(QRTLConstants.targetHiggsMassGeV - resonantMassGeV)
        higgsMode.frequencyHz = resonantFrequencyHz
        higgsMode.massGeV = resonantMassGeV
        higgsMode.energy = resonantModeEnergyJ
        higgsMode.amplitude = amp
        higgsMode.coherence = coh
        higgsMode.shellEnergy = energyState.shellEnergy
        higgsMode.shellInstability = energyState.shellInstability

        // Spin-0-like: high coherence, low charge asymmetry; not a new energy shell
        let spin0Like = coh > 0.5 && chargeAsymmetry < 0.35
        let nearTarget = resonantMassGeV > 0 && massDistanceFromTarget < 50.0
        // nearTarget is optional diagnostic; primary gates:
        let sufficientEnergy = resonantModeEnergyJ > QRTLConstants.activeEnergyThresholdJ
            || latticeEnergy > QRTLConstants.activeEnergyThresholdJ
        let measuredFrequency = resonantFrequencyHz > 0
        let shellWasDestabilized = collisionOccurred &&
            (energyState.shellInstability > 0.01 || collisionEnergyReleased)

        higgsMode.active =
            collisionOccurred &&
            sufficientEnergy &&
            spin0Like &&
            measuredFrequency &&
            shellWasDestabilized

        _ = nearTarget // available for stricter gate if desired

        if higgsMode.active {
            higgsNode.isHidden = false
            let vs = Float(max(0.05, min(2.5, amp * 8)))
            higgsNode.scale = SCNVector3(vs, vs, vs)
            higgsNode.opacity = CGFloat(max(0.15, min(1, coh)))
        } else {
            higgsNode.isHidden = true
        }

        if !energyState.isUnstable && higgsMode.active {
            higgsMode.decayProgress = min(1, higgsMode.decayProgress + dt * 0.15)
            if higgsMode.decayProgress >= 1 {
                higgsMode.active = false
                higgsNode.isHidden = true
            }
        }
    }

