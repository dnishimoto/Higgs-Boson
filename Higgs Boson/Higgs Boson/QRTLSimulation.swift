    // MARK: - Mechanical Phase Evolution
    //
    // Connects the mechanical lattice motion to the cell phase.
    // Phase is evolved from the cell's displacement, velocity,
    // twist, and restoring motion.
    //
    // This does not create energy or charge.

    private func updateCellPhase(dt: Double) {

        guard dt > 0.0 else {
            return
        }

        for index in cells.indices {

            let displacement =
                Double(length(cells[index].displacement))

            let velocity =
                Double(length(cells[index].velocity))

            let twist =
                cells[index].twist

            let localEnergy =
                max(0.0, cells[index].localEnergy)

            guard localEnergy >
                    QRTLConstants.activeEnergyThresholdJ
            else {
                continue
            }

            // Mechanical phase rate.
            //
            // Velocity provides the time-dependent component.
            // Displacement provides the restoring component.
            // Twist provides rotational coupling.

            let mechanicalRate =
                velocity +
                displacement * 10.0 +
                twist

            // Convert the mechanical rate into a stable
            // dimensionless phase increment.
            let phaseRate =
                mechanicalRate * 0.01

            cells[index].previousPhase =
                cells[index].phase

            cells[index].phase +=
                phaseRate * dt

            // Keep phase numerically bounded.
            cells[index].phase =
                cells[index].phase
                    .truncatingRemainder(
                        dividingBy: 2.0 * Double.pi
                    )

            // Update an unwrapped phase for diagnostics
            // and future frequency measurements.
            let phaseDifference =
                cells[index].phase -
                cells[index].previousPhase

            var wrappedDifference =
                phaseDifference

            if wrappedDifference > Double.pi {
                wrappedDifference -=
                    2.0 * Double.pi
            }

            if wrappedDifference < -Double.pi {
                wrappedDifference +=
                    2.0 * Double.pi
            }

            cells[index].unwrappedPhase +=
                wrappedDifference
        }
    }


