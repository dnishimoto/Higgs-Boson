    private func performFrame() {
        // Physics uses attosecond-scale step; visual quark/shell use separate clocks
        let physicalDt = QRTLConstants.timeStep
        for _ in 0..<QRTLConstants.physicsStepsPerFrame {
            updatePhysics(dt: physicalDt, visualDt: 1.0 / 60.0)
        }
        updateScene()
        objectWillChange.send()
    }
    func collisionEnergyDiagnostics() -> (
        totalLatticeEnergyJ: Double,
        coreLatticeEnergyJ: Double,
        massEnergyJ: Double,
        massEquivalentKg: Double,
        collisionOccurred: Bool
    ) {
        var totalLatticeEnergyJ = 0.0
        var coreLatticeEnergyJ = 0.0

        let centerX = (protonAX + protonBX) * 0.5

        for cell in cells {
            let cellEnergy = max(0.0, cell.localEnergy)
            totalLatticeEnergyJ += cellEnergy

            let dx = Double(cell.position.x) - centerX
            let distance = abs(dx)

            if distance <= collisionCoreRadius {
                coreLatticeEnergyJ += cellEnergy
            }
        }

        let massEnergyJ = max(0.0, collisionMassEnergyJ)
        let c = QRTLConstants.speedOfLight
        let massEquivalentKg = massEnergyJ / (c * c)

        return (
            totalLatticeEnergyJ: totalLatticeEnergyJ,
            coreLatticeEnergyJ: coreLatticeEnergyJ,
            massEnergyJ: massEnergyJ,
            massEquivalentKg: massEquivalentKg,
            collisionOccurred: collisionOccurred
        )
    }
    // MARK: - Physics pipeline

    func updatePhysics(
        dt: Double,
        visualDt: Double = 1.0 / 60.0
    ) {
        guard dt > 0 else { return }

        simulationTime += visualDt

        // 1. PROTON APPROACH
        if !collisionOccurred {
            updateProtonApproach(dt: visualDt)

            protonDistance = abs(protonBX - protonAX)

            if protonAState == "COLLISION" &&
               protonBState == "COLLISION" {
                performCollision()
            }
        }

        // ============================================================
        // 10^-22 SECOND SHELL DISSIPATION
        // ============================================================

        updateShellDissipationTrigger()

        // 4. EVOLVE EXISTING COLLISION ENERGY
        updateCollisionDynamics(dt: dt)

        // 5. SHELL DYNAMICS
        if !quarkCompressionActive && !quarkRepulsionActive {
            updateShellState(dt: visualDt)
        }

        // 6. QRTL LATTICE DYNAMICS
        updateLattice(dt: dt)

        // 7. PHASE / BORLAGRINO
        updateCellPhase(dt: dt)
        updateBorlagrinoFlow()

        // 8. COLLECTIVE RESONANCE
        measureCollectiveMode()
        recordCollectiveLatticeSignal()

        // 9. HIGGS-LIKE MODE
        updateHiggsLikeMode(dt: dt)

        // 10. ENERGY DIAGNOSTICS
        printCollisionEnergyState()
    }
    private func updateCollisionDynamics(dt: Double) {

        guard !cells.isEmpty else {
            return
        }

        // ============================================================
        // PHYSICAL TIMESTEP
        // ============================================================

        let physicsDt = QRTLConstants.timeStep

        guard physicsDt > 0.0,
              physicsDt.isFinite else {
            return
        }

        guard collisionKineticEnergyJ.isFinite,
              collisionKineticEnergyJ > 0.0,
              latticeExcited else {
            return
        }

        // ============================================================
        // ADVANCE COLLISION TIME
        // ============================================================

        collisionElapsedTime += physicsDt

        // ============================================================
        // QRTL ENERGY SHELL
        // ============================================================

        let shellWasReleasedBeforeUpdate = shellEnergyReleased

        updateEnergyShell()

        let shellJustReleased =
            !shellWasReleasedBeforeUpdate &&
            shellEnergyReleased

        // ============================================================
        // WAIT FOR SHELL RELEASE
        // ============================================================

        guard shellEnergyReleased else {
            return
        }

        // ============================================================
        // IMPORTANT:
        //
        // updateEnergyShell() converts the released shell energy
        // directly into lattice kinetic energy.
        //
        // Do NOT immediately apply another oscillator evolution
        // on the same release step.
        // ============================================================

        if shellJustReleased {

            latticeEnergy =
                totalMechanicalLatticeEnergy()

            currentLatticeEnergyJ =
                latticeEnergy

            currentLatticeEnergyGeV =
                latticeEnergy /
                QRTLConstants.joulesPerGeV

            currentLatticeEnergyTeV =
                currentLatticeEnergyGeV / 1_000.0

            print("""
            ============================================================
            SHELL RELEASE → KINETIC LATTICE ENERGY
            ============================================================
            Collision energy:
                \(collisionKineticEnergyJ) J

            Lattice kinetic/mechanical energy:
                \(latticeEnergy) J

            Lattice energy:
                \(currentLatticeEnergyGeV) GeV

            ============================================================
            """)

            return
        }

        // ============================================================
        // OSCILLATOR PARAMETERS
        // ============================================================

        let cellMassKg = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        let stiffnessNPerM = max(
            QRTLConstants.effectiveStiffnessNPerM,
            Double.leastNonzeroMagnitude
        )

        let omega = sqrt(
            stiffnessNPerM / cellMassKg
        )

        guard omega.isFinite,
              omega > 0.0 else {
            return
        }

        // ============================================================
        // NUMERICALLY STABLE PHASE INCREMENT
        //
        // Avoid using an enormous raw omega * dt directly when omega
        // is extremely large.
        // ============================================================

        let rawAngle = omega * physicsDt

        guard rawAngle.isFinite else {
            return
        }

        let twoPi = 2.0 * Double.pi

        let angle =
            rawAngle.truncatingRemainder(
                dividingBy: twoPi
            )

        let cosine = cos(angle)
        let sine = sin(angle)

        let omegaInverse = 1.0 / omega

        let damping =
            max(QRTLConstants.damping, 0.0)

        let dampingFactor =
            damping > 0.0
            ? exp(-damping * physicsDt)
            : 1.0

        // ============================================================
        // EVOLVE CELLS
        // ============================================================

        var energyBeforeLoop = 0.0
        var energyAfterEvolution = 0.0
        var energyAfterFloatConversion = 0.0

        var maximumEnergyIncrease = 0.0
        var maximumEnergyCell = -1

        var maximumDisplacement = 0.0
        var maximumVelocity = 0.0

        for index in cells.indices {

            // --------------------------------------------------------
            // CURRENT STATE
            // --------------------------------------------------------

            let currentDisplacement = SIMD3<Double>(
                Double(cells[index].displacement.x),
                Double(cells[index].displacement.y),
                Double(cells[index].displacement.z)
            )

            let currentVelocity = SIMD3<Double>(
                Double(cells[index].velocity.x),
                Double(cells[index].velocity.y),
                Double(cells[index].velocity.z)
            )

            let oldEnergy = physicalEnergy(
                displacement: cells[index].displacement,
                velocity: cells[index].velocity
            )

            energyBeforeLoop += oldEnergy

            // --------------------------------------------------------
            // ANALYTIC HARMONIC OSCILLATOR
            // --------------------------------------------------------

            let newDisplacement =
                currentDisplacement * cosine +
                currentVelocity *
                (omegaInverse * sine)

            var newVelocity =
                currentVelocity * cosine -
                currentDisplacement *
                (omega * sine)

            newVelocity *= dampingFactor

            // --------------------------------------------------------
            // MEASURE DYNAMICS
            // --------------------------------------------------------

            let displacementMagnitude =
                simd_length(newDisplacement)

            let velocityMagnitude =
                simd_length(newVelocity)

            maximumDisplacement =
                max(
                    maximumDisplacement,
                    displacementMagnitude
                )

            maximumVelocity =
                max(
                    maximumVelocity,
                    velocityMagnitude
                )

            // --------------------------------------------------------
            // ENERGY
            // --------------------------------------------------------

            let potentialEnergy =
                0.5 *
                stiffnessNPerM *
                simd_length_squared(newDisplacement)

            let kineticEnergy =
                0.5 *
                cellMassKg *
                simd_length_squared(newVelocity)

            let evolvedEnergy =
                potentialEnergy +
                kineticEnergy

            energyAfterEvolution +=
                evolvedEnergy

            let energyIncrease =
                evolvedEnergy - oldEnergy

            if energyIncrease > maximumEnergyIncrease {

                maximumEnergyIncrease =
                    energyIncrease

                maximumEnergyCell =
                    index
            }

            // --------------------------------------------------------
            // STORE STATE
            // --------------------------------------------------------

            cells[index].displacement =
                SIMD3<Float>(
                    Float(newDisplacement.x),
                    Float(newDisplacement.y),
                    Float(newDisplacement.z)
                )

            cells[index].velocity =
                SIMD3<Float>(
                    Float(newVelocity.x),
                    Float(newVelocity.y),
                    Float(newVelocity.z)
                )

            // --------------------------------------------------------
            // ENERGY AFTER FLOAT STORAGE
            // --------------------------------------------------------

            let storedEnergy =
                physicalEnergy(
                    displacement:
                        cells[index].displacement,
                    velocity:
                        cells[index].velocity
                )

            energyAfterFloatConversion +=
                storedEnergy

            // ========================================================
            // MODE CALCULATION
            // ========================================================

            let modeDirection = SIMD3<Double>(
                Double(cells[index].modeDirection.x),
                Double(cells[index].modeDirection.y),
                Double(cells[index].modeDirection.z)
            )

            let directionLength =
                simd_length(modeDirection)

            let normalizedModeDirection =
                directionLength > 0.0
                ? modeDirection / directionLength
                : SIMD3<Double>(
                    1.0,
                    0.0,
                    0.0
                )

            let modeCoordinate =
                simd_dot(
                    newDisplacement,
                    normalizedModeDirection
                )

            let modeVelocity =
                simd_dot(
                    newVelocity,
                    normalizedModeDirection
                )

            cells[index].modeCoordinate =
                modeCoordinate

            cells[index].modeVelocity =
                modeVelocity

            cells[index].modeAcceleration =
                -omega *
                omega *
                modeCoordinate

            // --------------------------------------------------------
            // MODE AMPLITUDE
            // --------------------------------------------------------

            let amplitudeSquared =
                modeCoordinate * modeCoordinate +
                pow(
                    modeVelocity / omega,
                    2.0
                )

            cells[index].amplitude =
                sqrt(
                    max(
                        0.0,
                        amplitudeSquared
                    )
                )

            // --------------------------------------------------------
            // PHASE
            // --------------------------------------------------------

            cells[index].previousPhase =
                cells[index].phase

            cells[index].phase =
                atan2(
                    modeVelocity,
                    omega * modeCoordinate
                )

            cells[index].unwrappedPhase +=
                cells[index].phase -
                cells[index].previousPhase

            // --------------------------------------------------------
            // AUTHORITATIVE LOCAL ENERGY
            // --------------------------------------------------------

            cells[index].localEnergy =
                max(
                    evolvedEnergy,
                    0.0
                )
        }

        // ============================================================
        // FINAL ENERGY
        // ============================================================

        latticeEnergy =
            totalMechanicalLatticeEnergy()

        currentLatticeEnergyJ =
            latticeEnergy

        currentLatticeEnergyGeV =
            latticeEnergy /
            QRTLConstants.joulesPerGeV

        currentLatticeEnergyTeV =
            currentLatticeEnergyGeV /
            1_000.0

        // ============================================================
        // DYNAMICS DEBUG
        // ============================================================

        print("""
        ============================================================
        DYNAMICS
        ============================================================
        Collision elapsed:
            \(collisionElapsedTime) s

        Shell released:
            \(shellEnergyReleased)

        Maximum displacement:
            \(maximumDisplacement) m

        Maximum velocity:
            \(maximumVelocity) m/s

        Energy before:
            \(energyBeforeLoop) J

        Energy after:
            \(energyAfterEvolution) J

        Float storage energy:
            \(energyAfterFloatConversion) J

        Lattice energy:
            \(latticeEnergy) J

        Lattice energy:
            \(currentLatticeEnergyGeV) GeV

        ============================================================
        """)
    }
    private func calculateBorlagrinoFlow(
        displacement: SIMD3<Float>,
        velocity: SIMD3<Float>,
        twist: Double,
        phase: Double,
        localEnergy: Double
    ) -> Double {

        guard localEnergy >
                QRTLConstants.activeEnergyThresholdJ
        else {
            return 0.0
        }

        let displacementMagnitude =
            Double(length(displacement))

        let velocityMagnitude =
            Double(length(velocity))

        // Mechanical direction.
        let motionTerm =
            velocityMagnitude +
            displacementMagnitude * 10.0

        // Rotational component.
        let twistTerm =
            twist

        // Phase circulation.
        let phaseTerm =
            sin(phase)

        // Normalize energy without allowing the very small
        // SI energy values to numerically suppress the flow.
        let energyNormalization =
            sqrt(
                localEnergy /
                QRTLConstants.activeEnergyThresholdJ
            )

        let normalizedEnergy =
            min(
                10.0,
                max(0.0, energyNormalization)
            )

        let flow =
            (
                motionTerm * phaseTerm
                +
                twistTerm * motionTerm
            ) * normalizedEnergy

        return flow
    }



 
    private func calculateChargeDensity(
        borlagrinoFlow: Double
    ) -> Double {

        let chargeScale = 1.0

        return borlagrinoFlow * chargeScale
    }


    // MARK: - Update Borlagrino Flow and Charge
    //
    // Calculates the flow for every active lattice cell and then
    // derives the corresponding local charge density.
    //
    // The result is stored in couplingState so the existing cell
    // structure does not need another stored property.

    private func updateBorlagrinoFlow() {

        guard !cells.isEmpty else {
            return
        }

        var totalAbsoluteFlow = 0.0
        var totalSignedCharge = 0.0

        for index in cells.indices {

            let cell = cells[index]

            guard cell.localEnergy >
                    QRTLConstants.activeEnergyThresholdJ
            else {
                cells[index].couplingState = 0.0
                continue
            }

            let flow =
                calculateBorlagrinoFlow(
                    displacement: cell.displacement,
                    velocity: cell.velocity,
                    twist: cell.twist,
                    phase: cell.phase,
                    localEnergy: cell.localEnergy
                )

            let charge =
                calculateChargeDensity(
                    borlagrinoFlow: flow
                )

            // Store a bounded representation of the local flow.
            cells[index].couplingState =
                tanh(flow)

            totalAbsoluteFlow += abs(flow)
            totalSignedCharge += charge
        }

        borlagrinoAverageMagnitude =
            totalAbsoluteFlow / Double(cells.count)

        netCharge =
            totalSignedCharge
    }



    private func updateProtonApproach(dt: Double) {

        // ============================================================
        // COLLISION ALREADY OCCURRED
        // ============================================================

        if collisionActive {

            protonAState = "COLLISION"
            protonBState = "COLLISION"

            protonDistance =
                abs(protonBX - protonAX)

            protonANode.position.x =
                Float(protonAX) *
                QRTLConstants.sceneScale

            protonBNode.position.x =
                Float(protonBX) *
                QRTLConstants.sceneScale

            return
        }

        // ============================================================
        // PROTON APPROACH
        // ============================================================

        let speed =
            QRTLConstants.protonSpeed

        protonAX += speed * dt
        protonBX -= speed * dt

        protonDistance =
            abs(protonBX - protonAX)

        // ============================================================
        // COLLISION DETECTION
        // ============================================================

        if protonDistance <=
            QRTLConstants.collisionDistance {

            collisionActive = true
            collisionCompleted = false
            collisionImpulseApplied = false

            collisionKineticEnergyJ =
                0.5 *
                QRTLConstants.protonMassKg *
                QRTLConstants.protonVelocityMPerS *
                QRTLConstants.protonVelocityMPerS

            depositedEnergyJ = 0.0
            latticeEnergy = 0.0
            ejectedEnergyJ = 0.0
            dissipatedEnergyJ = 0.0

            collectiveSignal.removeAll(
                keepingCapacity: true
            )

            protonAState = "COLLISION"
            protonBState = "COLLISION"

            print("""
            ============================================================
            QRTL PROTON COLLISION DETECTED
            ============================================================

            Proton A X: \(protonAX)
            Proton B X: \(protonBX)
            Separation: \(protonDistance)
            Threshold: \(QRTLConstants.collisionDistance)

            ============================================================
            """)

        } else {

            protonAState = "APPROACHING"
            protonBState = "APPROACHING"
        }

        // ============================================================
        // UPDATE VISUAL POSITIONS
        // ============================================================

        protonANode.position.x =
            Float(protonAX) *
            QRTLConstants.sceneScale

        protonBNode.position.x =
            Float(protonBX) *
            QRTLConstants.sceneScale
    }
    private func performCollision() {

        guard !collisionOccurred else { return }

        // ============================================================
        // MARK: - 1. INITIALIZE QUARK BREAKUP
        // ============================================================

        initializeCollisionQuarks()

        protonANode.isHidden = true
        protonBNode.isHidden = true

        for node in protonAQuarkNodes {
            node.isHidden = false
        }

        for node in protonBQuarkNodes {
            node.isHidden = false
        }

        updateQuarkScene()

        // ============================================================
        // MARK: - 2. COLLISION STATE
        // ============================================================

        collisionOccurred = true
        collisionTime = simulationTime
        collisionElapsedTime = 0.0

        quarkCompressionProgress = 0.0
        quarkRepulsionProgress = 0.0

        quarkCompressionActive = true
        quarkRepulsionActive = false

        collisionEnergyReleased = false
        quarksSeparated = false

        // ============================================================
        // MARK: - 3. ACTUAL INCOMING COLLISION ENERGY
        // ============================================================

        let incomingEnergyJ =
            QRTLConstants.collisionKineticEnergyJ

        guard incomingEnergyJ.isFinite,
              incomingEnergyJ > 0.0 else {

            print("""
            ERROR:
            Invalid collision energy:
            \(incomingEnergyJ) J
            """)

            return
        }

        // This is the actual physical energy entering the collision.
        collisionKineticEnergyJ = incomingEnergyJ

        collisionKineticEnergyGeV =
            incomingEnergyJ /
            QRTLConstants.joulePerGeV

        collisionKineticEnergyTeV =
            collisionKineticEnergyGeV /
            1_000.0

        // ============================================================
        // MARK: - 4. QRTL SHELL RECEIVES THE COLLISION ENERGY
        // ============================================================

        energyState.equilibriumShellEnergy =
            incomingEnergyJ

        energyState.shellEnergy =
            incomingEnergyJ

        energyState.shellInstability =
            1.0

        energyState.isUnstable =
            true

        energyState.deformation =
            1.0

        // ============================================================
        // MARK: - 5. 125 GeV HIGGS REFERENCE
        // ============================================================

        // IMPORTANT:
        // This is a reference/formation scale.
        // It is NOT the incoming collision energy.
        // It is NOT used to overwrite the collision energy.

        let higgsReferenceEnergyJ =
            QRTLConstants.targetHiggsMassGeV *
            QRTLConstants.joulePerGeV

        formationThresholdEnergy =
            higgsReferenceEnergyJ

        targetMassEnergyJ =
            higgsReferenceEnergyJ

        collisionMassEnergyJ =
            higgsReferenceEnergyJ

        collisionMassEquivalentKg =
            higgsReferenceEnergyJ /
            (
                QRTLConstants.speedOfLight *
                QRTLConstants.speedOfLight
