    }
    private func checkEnergyConservation(
        initialEnergy: Double
    ) -> Bool {

        guard initialEnergy > 0.0 else {
            return false
        }

        let ejectedEnergy =
            calculateEjectedParticleEnergy()

        let currentLatticeEnergy =
            totalMechanicalLatticeEnergy()

        let accountedEnergy =
            ejectedEnergy +
            currentLatticeEnergy

        guard accountedEnergy.isFinite else {
            return false
        }

        let difference =
            abs(
                initialEnergy -
                accountedEnergy
            )

        let relativeError =
            difference /
            max(
                abs(initialEnergy),
                1.0e-30
            )

        let tolerance = 0.05

        /*
        print("""
        
        ENERGY CONSERVATION
        
        Initial energy:
            \(initialEnergy) J
        
        Ejected energy:
            \(ejectedEnergy) J
        
        Lattice energy:
            \(currentLatticeEnergy) J
        
        Accounted energy:
            \(accountedEnergy) J
        
        Relative error:
            \(relativeError)
        
        """)
         */
        
        return relativeError <= tolerance
    }
    private func calculateStableShellEnergy() -> Double {

        guard !cells.isEmpty else {
            return 0.0
        }

        var shellEnergy = 0.0

        for cell in cells {

            let displacementMagnitude =
                Double(
                    length(cell.displacement)
                )

            let velocityMagnitude =
                Double(
                    length(cell.velocity)
                )

            let twistMagnitude =
                abs(
                    Double(cell.twist)
                )

            let phaseMagnitude =
                abs(
                    Double(cell.phase)
                )

            let displacementEnergy =
                0.5 *
                QRTLConstants.effectiveStiffnessNPerM *
                displacementMagnitude *
                displacementMagnitude

            let kineticEnergy =
                0.5 *
                QRTLConstants.effectiveMassKg *
                velocityMagnitude *
                velocityMagnitude

            let twistEnergy =
                0.5 *
                QRTLConstants.twistStiffness *
                twistMagnitude *
                twistMagnitude

            let phaseEnergy =
                0.5 *
                QRTLConstants.phaseStiffness *
                phaseMagnitude *
                phaseMagnitude

            shellEnergy +=
                displacementEnergy +
                kineticEnergy +
                twistEnergy +
                phaseEnergy
        }

        stableShellEnergyJ =
            max(
                0.0,
                shellEnergy
            )

        return stableShellEnergyJ
    }
    private func calculateEjectedParticleEnergy() -> Double {

        guard !ejectedUpQuarks.isEmpty else {
