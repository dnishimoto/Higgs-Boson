    func updatePhysics(dt: Double, visualDt: Double = 1.0 / 60.0) {
        guard dt > 0 else { return }
        simulationTime += visualDt

        if !collisionOccurred {
            updateProtonApproach(dt: visualDt)
            protonDistance = abs(protonBX - protonAX)
            if protonDistance <= QRTLConstants.collisionDistance {
                performCollision()
            }
            return
        }

        updateCollisionDynamics(dt: visualDt)
        if !quarkCompressionActive && !quarkRepulsionActive {
            updateShellState(dt: visualDt)
        }
        updateLattice(dt: dt)
        updateCellPhase(dt: dt)
        updateBorlagrinoFlow()
        measureCollectiveMode()
        recordCollectiveLatticeSignal()
        updateHiggsLikeMode(dt: dt)
        
        printCollisionEnergyState()
    }
    private func updateCollisionDynamics(dt: Double) {

        guard dt > 0.0 else { return }
        guard !cells.isEmpty else { return }

        let mass = QRTLConstants.effectiveMassKg
        let stiffness = QRTLConstants.effectiveStiffnessNPerM

        guard mass > 0.0, stiffness > 0.0 else {
            return
        }

        let omega = sqrt(stiffness / mass)

        guard omega.isFinite, omega > 0.0 else {
            return
        }

        // --------------------------------------------------------
        // Collision state comes from the simulation.
        // --------------------------------------------------------

        let kineticEnergyJ = collisionKineticEnergyJ
        let collisionCenter = collisionCenter

        guard kineticEnergyJ > 0.0 else {
            return
        }

        let radius = max(
            QRTLConstants.pumpRadius,
            1.0
        )

        // --------------------------------------------------------
        // 1. Convert collision kinetic energy into momentum.
        // --------------------------------------------------------

        let collisionVelocity = sqrt(
            max(
                0.0,
                2.0 * kineticEnergyJ / mass
            )
        )

        guard collisionVelocity.isFinite else {
            return
        }

        let collisionMomentum =
            mass * collisionVelocity

        // --------------------------------------------------------
        // 2. Calculate localized collision profile.
        // --------------------------------------------------------

        var weights = Array(
            repeating: 0.0,
            count: cells.count
        )

        var totalWeight = 0.0

        for index in cells.indices {

            let position = cells[index].position

            let dx = Double(
                position.x - collisionCenter.x
            )

            let dy = Double(
                position.y - collisionCenter.y
            )

            let dz = Double(
                position.z - collisionCenter.z
            )

            let distanceSquared =
                dx * dx +
                dy * dy +
                dz * dz

            let distance =
                sqrt(distanceSquared)

            guard distance <= radius else {
                continue
            }

            let normalizedDistance =
                distance / radius

            let weight = exp(
                -4.0 *
                normalizedDistance *
                normalizedDistance
            )

            weights[index] = weight
            totalWeight += weight
        }

        guard totalWeight > 0.0 else {
            return
        }

        // --------------------------------------------------------
        // 3. Apply localized mechanical impulse.
        // --------------------------------------------------------

        for index in cells.indices {

            let weight = weights[index]

            guard weight > 0.0 else {
                continue
            }

            let cell = cells[index]

            let offset = SIMD3<Float>(
                cell.position.x - collisionCenter.x,
                cell.position.y - collisionCenter.y,
                cell.position.z - collisionCenter.z
            )

            let dx = Double(offset.x)
            let dy = Double(offset.y)
            let dz = Double(offset.z)

            let distanceSquared =
                dx * dx +
                dy * dy +
                dz * dz

            let distance =
                sqrt(distanceSquared)

            // ----------------------------------------------------
            // Radial propagation direction.
            // ----------------------------------------------------

            var direction = SIMD3<Float>(
                0.0,
                0.0,
                0.0
            )

            if distance > 1.0e-15 {

                let inverseDistance =
                    Float(1.0 / distance)

                direction = SIMD3<Float>(
                    offset.x * inverseDistance,
                    offset.y * inverseDistance,
                    offset.z * inverseDistance
                )
            }

            // ----------------------------------------------------
            // 4. Distribute collision momentum.
            // ----------------------------------------------------

            let normalizedWeight =
                weight / totalWeight

            let localMomentum =
                collisionMomentum *
                normalizedWeight

            let localVelocity =
                localMomentum / mass

            let velocityKick =
                direction *
                Float(localVelocity)

            // ----------------------------------------------------
            // 5. Convert impulse into oscillator displacement.
            //
            // This initializes the mechanical state.
            // It does NOT assign a wavelength.
            // ----------------------------------------------------

            let displacementKick =
                velocityKick *
                Float(1.0 / omega)

            var newVelocity =
                cell.velocity +
                velocityKick

            var newDisplacement =
                cell.displacement +
                displacementKick

            // ----------------------------------------------------
            // 6. Numerical protection.
            // ----------------------------------------------------

            if !newVelocity.x.isFinite ||
               !newVelocity.y.isFinite ||
               !newVelocity.z.isFinite {

                newVelocity =
                    cell.velocity
            }

            if !newDisplacement.x.isFinite ||
               !newDisplacement.y.isFinite ||
               !newDisplacement.z.isFinite {

                newDisplacement =
                    cell.displacement
            }

            // ----------------------------------------------------
            // 7. Store mechanical state.
            // ----------------------------------------------------

            cells[index].velocity =
                newVelocity

            cells[index].displacement =
                newDisplacement

            // ----------------------------------------------------
            // 8. Calculate mode quantities from actual state.
            // ----------------------------------------------------

            let modeDirection =
                cell.modeDirection

            let modeCoordinate =
                Double(
                    dot(
                        newDisplacement,
                        modeDirection
                    )
                )

            let modeVelocity =
                Double(
                    dot(
                        newVelocity,
                        modeDirection
                    )
                )

            cells[index].modeCoordinate =
                modeCoordinate

            cells[index].modeVelocity =
                modeVelocity

            let amplitudeSquared =
                modeCoordinate * modeCoordinate +
                pow(
                    modeVelocity / omega,
                    2.0
                )

            cells[index].amplitude =
                sqrt(
                    max(
                        0.0,
                        amplitudeSquared
                    )
                )

            // ----------------------------------------------------
            // 9. Calculate actual mechanical energy.
            // ----------------------------------------------------

            cells[index].localEnergy =
                physicalEnergy(
                    displacement: newDisplacement,
                    velocity: newVelocity
                )

            // ----------------------------------------------------
            // 10. Phase is intentionally NOT forced here.
            //
            // updateLattice(dt:) evolves phase naturally.
            // ----------------------------------------------------
        }

        // --------------------------------------------------------
        // 11. Recalculate total lattice energy.
        // --------------------------------------------------------

        latticeEnergy =
            totalMechanicalLatticeEnergy()

        print("""
        
        COLLISION DYNAMIC
        
        dt:
            \(dt) s
        
        Collision kinetic energy:
            \(kineticEnergyJ) J
        
        Collision velocity:
            \(collisionVelocity) m/s
        
        Collision momentum:
            \(collisionMomentum) kg·m/s
        
        Collision center:
            \(collisionCenter)
        
        Pump radius:
            \(radius)
        
        Resulting lattice energy:
            \(latticeEnergy) J
        """)
    }
    private func calculateBorlagrinoFlow(
        displacement: SIMD3<Float>,
        velocity: SIMD3<Float>,
        twist: Double,
        phase: Double,
        localEnergy: Double
    ) -> Double {

        guard localEnergy >
                QRTLConstants.activeEnergyThresholdJ
        else {
            return 0.0
        }

        let displacementMagnitude =
            Double(length(displacement))

        let velocityMagnitude =
            Double(length(velocity))

        // Mechanical direction.
        let motionTerm =
            velocityMagnitude +
            displacementMagnitude * 10.0

        // Rotational component.
        let twistTerm =
            twist

        // Phase circulation.
        let phaseTerm =
            sin(phase)

        // Normalize energy without allowing the very small
        // SI energy values to numerically suppress the flow.
        let energyNormalization =
            sqrt(
                localEnergy /
                QRTLConstants.activeEnergyThresholdJ
            )

        let normalizedEnergy =
            min(
                10.0,
                max(0.0, energyNormalization)
            )

        let flow =
            (
                motionTerm * phaseTerm
                +
                twistTerm * motionTerm
            ) * normalizedEnergy

        return flow
    }



 
    private func calculateChargeDensity(
        borlagrinoFlow: Double
    ) -> Double {

        let chargeScale = 1.0

        return borlagrinoFlow * chargeScale
    }


    // MARK: - Update Borlagrino Flow and Charge
    //
    // Calculates the flow for every active lattice cell and then
    // derives the corresponding local charge density.
    //
    // The result is stored in couplingState so the existing cell
    // structure does not need another stored property.

    private func updateBorlagrinoFlow() {

        guard !cells.isEmpty else {
            return
        }

        var totalAbsoluteFlow = 0.0
        var totalSignedCharge = 0.0

        for index in cells.indices {

            let cell = cells[index]

            guard cell.localEnergy >
                    QRTLConstants.activeEnergyThresholdJ
            else {
                cells[index].couplingState = 0.0
                continue
            }

            let flow =
                calculateBorlagrinoFlow(
                    displacement: cell.displacement,
                    velocity: cell.velocity,
                    twist: cell.twist,
                    phase: cell.phase,
                    localEnergy: cell.localEnergy
                )

            let charge =
                calculateChargeDensity(
                    borlagrinoFlow: flow
                )

            // Store a bounded representation of the local flow.
            cells[index].couplingState =
                tanh(flow)

            totalAbsoluteFlow += abs(flow)
            totalSignedCharge += charge
        }

        borlagrinoAverageMagnitude =
            totalAbsoluteFlow / Double(cells.count)

        netCharge =
            totalSignedCharge
    }


