    private func initializeCollision(
        kineticEnergyJ: Double,
        collisionPosition: Int
    ) {
        // --------------------------------------------------------
        // RESET COLLISION STATE
        // --------------------------------------------------------

        collisionActive = true
        collisionCompleted = false

        collectiveSignal.removeAll(keepingCapacity: true)

        naturalAngularFrequency = 0.0
        naturalFrequencyHz = 0.0

        resonantModeAmplitude = 0.0
        resonantModeEnergy = 0.0

        higgsLikeModeDetected = false
        resonancePersistence = 0.0

        // --------------------------------------------------------
        // STORE COLLISION ENERGY
        // --------------------------------------------------------

        collisionKineticEnergyJ = max(kineticEnergyJ, 0.0)

        // --------------------------------------------------------
        // CLEAR PREVIOUS LATTICE MOTION
        // --------------------------------------------------------

        for index in cells.indices {

            // Fixed lattice position is NOT changed.
            // position is a let constant in QRTLCell.

            cells[index].displacement = .zero
            cells[index].velocity = .zero

            cells[index].twist = 0.0
            cells[index].phase = 0.0
            cells[index].amplitude = 0.0

            cells[index].localEnergy = 0.0
            cells[index].localStrain = 0.0
            cells[index].couplingState = 0.0

            cells[index].modeCoordinate = 0.0
            cells[index].modeVelocity = 0.0
            cells[index].modeAcceleration = 0.0
            cells[index].modeDirection = .zero

            cells[index].previousPhase = 0.0
            cells[index].unwrappedPhase = 0.0

            cells[index].borlagrinoFlow = .zero
            cells[index].charge = 0.0
        }

        // --------------------------------------------------------
        // VALIDATE LATTICE
        // --------------------------------------------------------

        guard !cells.isEmpty else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // COLLISION LOCATION
        // --------------------------------------------------------

        let centerIndex = min(
            max(collisionPosition, 0),
            cells.count - 1
        )

        // --------------------------------------------------------
        // LOCALIZE COLLISION ENERGY
        // --------------------------------------------------------

        let radius = max(
            QRTLConstants.collisionRadius,
            1.0
        )

        var totalWeight = 0.0

        var weights = [Double](
            repeating: 0.0,
            count: cells.count
        )

        let centerX = Double(
            cells[centerIndex].position.x
        )

        let centerY = Double(
            cells[centerIndex].position.y
        )

        for index in cells.indices {

            let dx =
                Double(cells[index].position.x) - centerX

            let dy =
                Double(cells[index].position.y) - centerY

            let distanceSquared =
                dx * dx + dy * dy

            let weight = exp(
                -distanceSquared /
                (2.0 * radius * radius)
            )

            weights[index] = weight
            totalWeight += weight
        }

        guard totalWeight > 0.0 else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // CONVERT COLLISION ENERGY INTO LATTICE DISPLACEMENT
        //
        // E = 1/2 k x²
        //
        // x = sqrt(2E/k)
        // --------------------------------------------------------

        let stiffness = max(
            QRTLConstants.effectiveStiffnessNPerM,
            Double.leastNonzeroMagnitude
        )

        for index in cells.indices {

            let normalizedWeight =
                weights[index] / totalWeight

            let localEnergy =
                collisionKineticEnergyJ * normalizedWeight

            cells[index].localEnergy =
                localEnergy

            let displacementMagnitude =
                sqrt(
                    max(
                        2.0 * localEnergy / stiffness,
                        0.0
                    )
                )

            // Radial collision disturbance.
            let direction: Double =
                index == centerIndex ? 1.0 : 0.5

            let displacement =
                displacementMagnitude * direction

            // Dynamic displacement.
            cells[index].displacement.x =
                Float(displacement)

            // Store amplitude consistently with displacement.
            cells[index].amplitude =
                displacement

            // Local strain.
            cells[index].localStrain =
                displacement /
                max(
                    QRTLConstants.cellSpacing,
                    Double.leastNonzeroMagnitude
                )
        }

        // --------------------------------------------------------
        // INITIAL COLLISION SIGNAL
        // --------------------------------------------------------

        let initialSignal =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        collectiveSignal.append(
            initialSignal
        )

        // --------------------------------------------------------
        // INITIAL MECHANICAL REFERENCE
        //
        // This does not assign the collision wavelength.
        // The propagated collective signal is analyzed later.
        // --------------------------------------------------------

        let mass = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        naturalAngularFrequency =
            sqrt(stiffness / mass)

        naturalFrequencyHz =
            naturalAngularFrequency /
            (2.0 * Double.pi)

        // --------------------------------------------------------
        // DEBUG VALUES
        // --------------------------------------------------------

        let initializedEnergy =
            cells.reduce(0.0) { total, cell in
                total + cell.localEnergy
            }

        let initializedDisplacement =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        let centerCell =
            cells[centerIndex]

        print("""
        
        ========================================================
        COLLISION INITIALIZATION DEBUG
        ========================================================

        Collision kinetic energy:
            \(collisionKineticEnergyJ) J

        Localized lattice energy:
            \(initializedEnergy) J

        Energy ratio:
            \(collisionKineticEnergyJ > 0.0
                ? initializedEnergy / collisionKineticEnergyJ
                : 0.0)

        Total displacement:
            \(initializedDisplacement)

        Initial signal:
            \(initialSignal)

        Center cell:
            \(centerIndex)

        Center displacement:
            \(centerCell.displacement)

        Center local energy:
            \(centerCell.localEnergy)

        Center strain:
            \(centerCell.localStrain)

        Natural angular frequency:
            \(naturalAngularFrequency)

        Natural frequency:
            \(naturalFrequencyHz) Hz

        ========================================================
        """)
    }
    private func applyProtonCollision(
        kineticEnergyJ: Double,
        collisionCenter: SIMD3<Float>
    ) {

        guard kineticEnergyJ > 0.0 else { return }
        guard !cells.isEmpty else { return }

        let mass = QRTLConstants.effectiveMassKg
        let stiffness = QRTLConstants.effectiveStiffnessNPerM

        guard mass > 0.0, stiffness > 0.0 else {
            return
        }

        let omega = sqrt(stiffness / mass)

        guard omega.isFinite, omega > 0.0 else {
            return
        }

        let radius = max(
            QRTLConstants.pumpRadius,
            1.0
        )

        // --------------------------------------------------------
        // Convert collision energy into collision velocity.
        // --------------------------------------------------------

        let collisionVelocity = sqrt(
            max(
                0.0,
                2.0 * kineticEnergyJ / mass
            )
        )

        guard collisionVelocity.isFinite else {
            return
        }

        let collisionMomentum =
            mass * collisionVelocity

        // --------------------------------------------------------
        // Calculate spatial weights first.
        //
        // Cells near the collision receive the strongest
        // disturbance. Cells farther away receive less.
        // --------------------------------------------------------

        var weights = Array(
            repeating: 0.0,
            count: cells.count
        )

        var totalWeight = 0.0

        for index in cells.indices {

            let position = cells[index].position

            let dx =
                Double(position.x - collisionCenter.x)

            let dy =
                Double(position.y - collisionCenter.y)

            let dz =
                Double(position.z - collisionCenter.z)

            let distanceSquared =
                dx * dx +
                dy * dy +
                dz * dz

            let distance =
                sqrt(distanceSquared)

            if distance <= radius {

                let normalizedDistance =
                    distance / radius

                let weight = exp(
                    -4.0 *
                    normalizedDistance *
                    normalizedDistance
                )

                weights[index] = weight
                totalWeight += weight
            }
        }

        guard totalWeight > 0.0 else {
            return
        }

        // --------------------------------------------------------
        // Apply localized radial impulse.
        // --------------------------------------------------------

        for index in cells.indices {

            let weight = weights[index]

            guard weight > 0.0 else {
                continue
            }

            let cell = cells[index]

            let offset = SIMD3<Float>(
                cell.position.x - collisionCenter.x,
                cell.position.y - collisionCenter.y,
                cell.position.z - collisionCenter.z
            )

            let offsetX = Double(offset.x)
            let offsetY = Double(offset.y)
            let offsetZ = Double(offset.z)

            let distanceSquared =
                offsetX * offsetX +
                offsetY * offsetY +
                offsetZ * offsetZ

            let distance =
                sqrt(distanceSquared)

            // ----------------------------------------------------
            // Radial direction.
            // ----------------------------------------------------

            var direction =
                SIMD3<Float>(
                    0.0,
                    0.0,
                    0.0
                )

            if distance > 1.0e-15 {

                let inverseDistance =
                    Float(1.0 / distance)

                direction = SIMD3<Float>(
                    offset.x * inverseDistance,
                    offset.y * inverseDistance,
                    offset.z * inverseDistance
                )
            }

            // ----------------------------------------------------
            // Normalize the local collision weight.
            // ----------------------------------------------------

            let normalizedWeight =
                weight / totalWeight

            let localMomentum =
                collisionMomentum *
                normalizedWeight

            let localVelocityMagnitude =
                localMomentum / mass

            let velocityMagnitudeFloat =
                Float(localVelocityMagnitude)

            let velocityKick =
                direction *
                velocityMagnitudeFloat

            // ----------------------------------------------------
            // Convert the velocity kick into an initial
            // displacement.
            // ----------------------------------------------------

            let displacementScale =
                Float(1.0 / omega)

            let displacementKick =
                velocityKick *
                displacementScale

            // ----------------------------------------------------
            // Add the collision to the existing state.
            // ----------------------------------------------------

            var newVelocity =
                cell.velocity +
                velocityKick

            var newDisplacement =
                cell.displacement +
                displacementKick

            // ----------------------------------------------------
            // Safety checks.
            // ----------------------------------------------------

            if !newVelocity.x.isFinite ||
               !newVelocity.y.isFinite ||
               !newVelocity.z.isFinite {

                newVelocity = cell.velocity
            }

            if !newDisplacement.x.isFinite ||
               !newDisplacement.y.isFinite ||
               !newDisplacement.z.isFinite {

                newDisplacement =
                    cell.displacement
            }

            // ----------------------------------------------------
            // Store mechanical state.
            // ----------------------------------------------------

            cells[index].velocity =
                newVelocity

            cells[index].displacement =
                newDisplacement

            // ----------------------------------------------------
            // Do NOT synchronize phase here.
            //
            // Phase will be calculated from the mechanical
            // motion during updateLattice().
            // ----------------------------------------------------

            let modeDirection =
                cell.modeDirection

            let modeCoordinate =
                Double(
                    dot(
                        newDisplacement,
                        modeDirection
                    )
                )

            let modeVelocity =
                Double(
                    dot(
                        newVelocity,
                        modeDirection
                    )
                )

            cells[index].modeCoordinate =
                modeCoordinate

            cells[index].modeVelocity =
                modeVelocity

            let amplitudeSquared =
                modeCoordinate * modeCoordinate +
                pow(
                    modeVelocity / omega,
                    2.0
                )

            cells[index].amplitude =
                sqrt(
                    max(
                        0.0,
                        amplitudeSquared
                    )
                )

            cells[index].localEnergy =
                physicalEnergy(
                    displacement: newDisplacement,
                    velocity: newVelocity
                )
        }

        // --------------------------------------------------------
        // Recalculate actual mechanical lattice energy.
        //
        // Do NOT add kineticEnergyJ again here.
        // --------------------------------------------------------

        latticeEnergy =
            totalMechanicalLatticeEnergy()

        print("""
        
        COLLISION IMPULSE

        Collision energy:
            \(kineticEnergyJ) J

        Collision velocity:
            \(collisionVelocity) m/s

        Collision momentum:
            \(collisionMomentum) kg·m/s

        Collision center:
            \(collisionCenter)

        Pump radius:
            \(radius)

        Active lattice energy:
            \(latticeEnergy) J

        """)
    }
    private func updateQuarkCollisionState(dt: Double) {
        guard collisionOccurred else { return }
        let progress = min(1, collisionElapsedTime / quarkVisualDuration)
        if progress < 1 {
            let compression = sin(progress * .pi * 0.5)
            for i in protonAQuarks.indices {
                protonAQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonAQuarks[i].position.x
                protonAQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            for i in protonBQuarks.indices {
                protonBQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonBQuarks[i].position.x
                protonBQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            return
        }
        let repulsionProgress = min(1, (collisionElapsedTime - quarkVisualDuration) / quarkVisualDuration)
        let repulsion = sin(repulsionProgress * .pi * 0.5)
        for i in protonAQuarks.indices {
            let o = protonAQuarks[i].originalPosition
            protonAQuarks[i].position.x = o.x - repulsion * 1.5
            protonAQuarks[i].velocity.x = -repulsion
        }
        for i in protonBQuarks.indices {
            let o = protonBQuarks[i].originalPosition
            protonBQuarks[i].position.x = o.x + repulsion * 1.5
            protonBQuarks[i].velocity.x = repulsion
        }
        if repulsionProgress >= 1 { quarksSeparated = true }
    }

    private func applyQuarkCompression(compression: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = compression * influence
            cells[i].localStrain = min(1, cells[i].localStrain + f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.05)
            cells[i].twist += f * QRTLConstants.twistAttractStrength
        }
        // Shell tracks full collision budget; instability follows compression
        energyState.shellInstability = max(energyState.shellInstability, compression)
        energyState.shellEnergy = QRTLConstants.collisionKineticEnergyJ
    }

    private func applyQuarkRepulsion(repulsion: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = repulsion * influence
            cells[i].localStrain = max(0, cells[i].localStrain - f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.1)
            cells[i].twist -= f * QRTLConstants.twistRepelStrength
        }
    }

    /// Competing twist attract (confine) / repel (release) near the core.
    private func applyTwistAttractionRepulsion(compression: Double, repulsion: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let attract = compression * influence * QRTLConstants.twistAttractStrength
            let repel = repulsion * influence * QRTLConstants.twistRepelStrength
            cells[i].twist += attract - repel
            // Slight radial velocity bias without inventing energy budget
            let sign: Float = cells[i].position.x >= 0 ? 1 : -1
            cells[i].velocity.x += sign * Float(attract - repel) * 0.01
            cells[i].velocity.x = max(
                -Float(QRTLConstants.maxLatticeVelocity),
                min(Float(QRTLConstants.maxLatticeVelocity), cells[i].velocity.x)
            )
        }
    }

    private func releaseCollisionEnergy(amount: Double) {
        guard !cells.isEmpty else { return }
        let release = collisionCoreEnergyJ * amount * 0.001
        collisionReleasedEnergyJ += release
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            let influence = exp(-(dx * dx) / (collisionCoreRadius * collisionCoreRadius))
            cells[i].amplitude = min(1, cells[i].amplitude + influence * amount * 0.02)
        }
    }

    private func restoreCollisionSymmetry() {
        energyState.shellInstability = 0
        energyState.isUnstable = false
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        collisionEnergySymmetry = 1
        collisionMassEnergyJ = 0
        collisionMassEquivalentKg = 0
        collisionCoreEnergyJ = 0
    }

    private func updateShellState(dt: Double) {
        guard energyState.isUnstable else { return }
        let rate = dt / shellRelaxationVisualSeconds
        energyState.shellInstability = max(0, energyState.shellInstability - rate)
        energyState.deformation = energyState.shellInstability
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        if energyState.shellInstability < 0.05 {
            energyState.isUnstable = false
        }
        let s = Float(1 + energyState.shellInstability * 0.9)
        protonAShellNode.scale = SCNVector3(s, s, s)
        protonBShellNode.scale = SCNVector3(s, s, s)
    }

    // MARK: - Lattice mass–spring CA

    private func physicalEnergy(displacement: SIMD3<Float>, velocity: SIMD3<Float>) -> Double {
        let spacing = QRTLConstants.latticeCellSpacingMeters
        let x = Double(simd_length(displacement)) * spacing
        let v = Double(simd_length(velocity)) * spacing
        guard x.isFinite, v.isFinite else { return 0 }
        let pot = 0.5 * QRTLConstants.effectiveStiffnessNPerM * x * x
        let kin = 0.5 * QRTLConstants.effectiveMassKg * v * v
        let e = pot + kin
        return e.isFinite ? max(0, e) : 0
    }

    func totalMechanicalLatticeEnergy() -> Double {
        cells.reduce(0.0) { $0 + physicalEnergy(displacement: $1.displacement, velocity: $1.velocity) }
    }


    private func updateLattice(dt: Double) {

        guard !cells.isEmpty else {
            return
        }

        // ============================================================
        // PHYSICAL LATTICE STEP
        //
        // SceneKit's dt is only the visualization interval.
        // The lattice evolves using the QRTL physical timestep.
        //
        // PROTON COLLISION
        //       ↓
        // kinetic energy
        //       ↓
        // momentum / impulse
        //       ↓
        // localized velocity
        //       ↓
        // localized displacement
        //       ↓
        // kinetic + potential energy
        //       ↓
        // restoring force + neighbor coupling
        //       ↓
        // propagation
        //       ↓
        // phase evolution
        //       ↓
        // collective signal
        //       ↓
        // FFT / spectral analysis
        //       ↓
        // natural modes
        // ============================================================

        let h =
            QRTLConstants.timeStep

        guard h > 0.0 else {
            return
        }

        let mass =
            QRTLConstants.effectiveMassKg

        let stiffness =
            QRTLConstants.effectiveStiffnessNPerM

        guard mass > 0.0,
              stiffness > 0.0
        else {
            return
        }

        // ============================================================
        // NATURAL ANGULAR FREQUENCY
        // ============================================================

        let omega =
            sqrt(
                stiffness /
                mass
            )

        guard omega.isFinite,
              omega > 0.0
        else {
            return
        }

        // ============================================================
        // PROTON COLLISION → MOMENTUM / IMPULSE
        //
        // IMPORTANT:
        // This executes only once for each collision.
        //
        // applyProtonCollision() converts the collision kinetic energy
        // into actual cell velocity and displacement.
        // ============================================================

        if !collisionImpulseApplied &&
           depositedEnergyJ > 0.0 {

            applyProtonCollision(
                kineticEnergyJ:
                    depositedEnergyJ,
                collisionCenter:
                    collisionCenter
            )

            collisionImpulseApplied =
                true
        }

        // ============================================================
        // ANALYTIC OSCILLATOR
        //
        // x(t+h) = x cos(ωh)
        //          + v/ω sin(ωh)
        //
        // v(t+h) = v cos(ωh)
        //          - ωx sin(ωh)
        //
        // This preserves stability for the extremely stiff QRTL
        // oscillator.
        // ============================================================

        let angle =
            omega * h

        let cosAngle =
            cos(angle)

        let sinAngle =
            sin(angle)

        let omegaInverse =
            1.0 / omega

        // ============================================================
        // DAMPING
        // ============================================================

        let damping =
            exp(
                -QRTLConstants.damping *
                h /
                QRTLConstants.timeStep
            )

        // ============================================================
        // LIMITS
        // ============================================================

        let maxDisplacement =
            max(
                Double(
                    QRTLConstants.maxLatticeDisplacement
                ),
                1.0e-12
            )

        let maxVelocity =
            max(
                Double(
                    QRTLConstants.maxLatticeVelocity
                ),
                1.0e-12
            )

        // ============================================================
        // SYNCHRONOUS LATTICE UPDATE
        //
        // Every cell reads the previous lattice state.
        // ============================================================

        var next =
            cells

        // ============================================================
        // UPDATE EACH CELL
        // ============================================================

        for index in cells.indices {

            let cell =
                cells[index]

            // ========================================================
            // NEIGHBOR AVERAGES
            // ========================================================

            var neighborDisplacement =
                SIMD3<Double>(
                    0.0,
                    0.0,
                    0.0
                )

            var neighborVelocity =
                SIMD3<Double>(
                    0.0,
                    0.0,
                    0.0
                )

            var neighborTwist =
                0.0

            var neighborStrain =
                0.0

            if !cell.neighbors.isEmpty {

                for neighborIndex in cell.neighbors {

                    guard cells.indices.contains(
                        neighborIndex
                    )
                    else {
                        continue
                    }

                    let neighbor =
                        cells[neighborIndex]

                    neighborDisplacement +=
                        SIMD3<Double>(
                            Double(
                                neighbor.displacement.x
                            ),
                            Double(
                                neighbor.displacement.y
                            ),
                            Double(
                                neighbor.displacement.z
                            )
                        )

                    neighborVelocity +=
                        SIMD3<Double>(
                            Double(
                                neighbor.velocity.x
                            ),
                            Double(
                                neighbor.velocity.y
                            ),
                            Double(
                                neighbor.velocity.z
                            )
                        )

                    neighborTwist +=
                        neighbor.twist

                    neighborStrain +=
                        neighbor.localStrain
                }

                let count =
                    Double(
                        cell.neighbors.count
                    )

                if count > 0.0 {

                    neighborDisplacement /=
                        count

                    neighborVelocity /=
                        count

                    neighborTwist /=
                        count

                    neighborStrain /=
                        count
                }
            }

            // ========================================================
            // CURRENT MECHANICAL STATE
            // ========================================================

            let x =
                SIMD3<Double>(
                    Double(
                        cell.displacement.x
                    ),
                    Double(
                        cell.displacement.y
                    ),
                    Double(
                        cell.displacement.z
                    )
                )

            let v =
                SIMD3<Double>(
                    Double(
                        cell.velocity.x
                    ),
                    Double(
                        cell.velocity.y
                    ),
                    Double(
                        cell.velocity.z
                    )
                )

            // ========================================================
            // ANALYTIC SELF OSCILLATION
            // ========================================================

            var newX =
                x *
                cosAngle
                +
                v *
                (
                    omegaInverse *
                    sinAngle
                )

            var newV =
                v *
                cosAngle
                -
                x *
                (
                    omega *
                    sinAngle
                )

            // ========================================================
            // NEIGHBOR COUPLING
            //
            // The collision disturbance is transferred between
            // neighboring cells.
            // ========================================================

            let coupling =
                QRTLConstants.coupling

            let displacementDelta =
                neighborDisplacement -
                newX

            let velocityDelta =
                neighborVelocity -
                newV

            let displacementKick =
                displacementDelta *
                coupling

            let velocityKick =
                velocityDelta *
                coupling

            newX +=
                displacementKick *
                h

            newV +=
                velocityKick *
                h

            // ========================================================
            // DAMPING
            // ========================================================

            newV *=
                damping

            // ========================================================
            // SAFETY
            // ========================================================

            if !newX.x.isFinite ||
               !newX.y.isFinite ||
               !newX.z.isFinite {

                newX =
                    x
            }

            if !newV.x.isFinite ||
               !newV.y.isFinite ||
               !newV.z.isFinite {

                newV =
                    v
            }

            // ========================================================
            // DISPLACEMENT LIMIT
            // ========================================================

            let displacementMagnitude =
                simd_length(
                    newX
                )

            if displacementMagnitude >
               maxDisplacement {

                let scale =
                    maxDisplacement /
                    displacementMagnitude

                newX *=
                    scale
            }

            // ========================================================
            // VELOCITY LIMIT
            // ========================================================

            let velocityMagnitude =
                simd_length(
                    newV
                )

            if velocityMagnitude >
               maxVelocity {

                let scale =
                    maxVelocity /
                    velocityMagnitude

                newV *=
                    scale
            }

            // ========================================================
            // TWIST OSCILLATION
            // ========================================================

            let twist =
                cell.twist

            let twistAcceleration =
                QRTLConstants.twistCoupling *
                (
                    neighborTwist -
                    twist
                )
                -
                QRTLConstants.twistRestoring *
                twist

            var newTwist =
                twist +
                twistAcceleration *
                h

            newTwist *=
                damping

            if !newTwist.isFinite {
                newTwist =
                    twist
            }

            // ========================================================
            // MODE DIRECTION
            // ========================================================

            let direction =
                simd_length(
                    cell.modeDirection
                ) > 0.0001
                ? cell.modeDirection
                : SIMD3<Float>(
                    1.0,
                    0.0,
                    0.0
                )

            let directionDouble =
                SIMD3<Double>(
                    Double(
                        direction.x
                    ),
                    Double(
                        direction.y
                    ),
                    Double(
                        direction.z
                    )
                )

            // ========================================================
            // COLLECTIVE MODE COORDINATE
            // ========================================================

            let modeCoordinate =
                simd_dot(
                    newX,
                    directionDouble
                )

            let modeVelocity =
                simd_dot(
                    newV,
                    directionDouble
                )

            // ========================================================
            // PHASE
            //
            // Phase comes from the actual mechanical state.
            //
            // This allows different cells to develop different phases
            // as the disturbance propagates.
            // ========================================================

            let normalizedVelocity =
                modeVelocity *
                omegaInverse

            let oscillatorAmplitude =
                sqrt(
                    modeCoordinate *
                    modeCoordinate
                    +
                    normalizedVelocity *
                    normalizedVelocity
                )

            var phase =
                cell.phase

            if oscillatorAmplitude >
               1.0e-30 {

                phase =
                    atan2(
                        modeVelocity,
                        omega *
                        modeCoordinate
                    )
            }

            let phaseDelta =
                wrapPhase(
                    phase -
                    cell.phase
                )

            // ========================================================
            // AMPLITUDE
            // ========================================================

            let amplitude =
                oscillatorAmplitude

            // ========================================================
            // STRAIN
            // ========================================================

            let displacementFraction =
                min(
                    1.0,
                    simd_length(
                        newX
                    )
                    /
                    maxDisplacement
                )

            let strain =
                min(
                    1.0,
                    displacementFraction
                    +
                    abs(
                        neighborStrain -
                        displacementFraction
                    )
                    *
                    QRTLConstants.strainCoupling
                )

            // ========================================================
            // MECHANICAL ENERGY
            //
            // Energy is calculated from the actual displacement and
            // velocity produced by the collision and subsequent
            // propagation.
            // ========================================================

            let localEnergy =
                physicalEnergy(
                    displacement:
                        SIMD3<Float>(
                            Float(
                                newX.x
                            ),
                            Float(
                                newX.y
                            ),
                            Float(
                                newX.z
                            )
                        ),
                    velocity:
                        SIMD3<Float>(
                            Float(
                                newV.x
                            ),
                            Float(
                                newV.y
                            ),
                            Float(
                                newV.z
                            )
                        )
                )

            // ========================================================
            // COUPLING STATE
            // ========================================================

            let displacementDifference =
                simd_length(
                    neighborDisplacement -
                    newX
                )

            let couplingIncrement =
                coupling
                *
                min(
                    1.0,
                    displacementDifference /
                    maxDisplacement
                )
                *
                h
                /
                QRTLConstants.timeStep

            let couplingState =
                min(
                    1.0,
                    max(
                        0.0,
                        cell.couplingState
                        +
                        couplingIncrement
                    )
                )

            // ========================================================
            // COMMIT CELL
            // ========================================================

            next[index].displacement =
                SIMD3<Float>(
                    Float(
                        newX.x
                    ),
                    Float(
                        newX.y
                    ),
                    Float(
                        newX.z
                    )
                )

            next[index].velocity =
                SIMD3<Float>(
                    Float(
                        newV.x
                    ),
                    Float(
                        newV.y
                    ),
                    Float(
                        newV.z
                    )
                )

            next[index].modeCoordinate =
                modeCoordinate

            next[index].modeVelocity =
                modeVelocity

            next[index].modeAcceleration =
                abs(
                    modeVelocity -
                    cell.modeVelocity
                )
                /
                h

            next[index].twist =
                newTwist

            next[index].previousPhase =
                cell.phase

            next[index].phase =
                phase

            next[index].unwrappedPhase =
                cell.unwrappedPhase
                +
                phaseDelta

            next[index].amplitude =
                amplitude

            next[index].localStrain =
                strain

            next[index].localEnergy =
                max(
                    0.0,
                    localEnergy
                )

            next[index].couplingState =
                couplingState

            next[index].modeDirection =
                direction

            next[index].borlagrinoFlow =
                cell.borlagrinoFlow

            next[index].charge =
                cell.charge
        }

        // ============================================================
        // SIMULTANEOUSLY COMMIT ALL CELLS
        // ============================================================

        cells =
            next

        // ============================================================
        // TOTAL LATTICE ENERGY
        // ============================================================

        latticeEnergy =
            totalMechanicalLatticeEnergy()

        // ============================================================
        // DISSIPATION
        // ============================================================

        dissipatedEnergyJ =
            max(
                0.0,
                depositedEnergyJ -
                latticeEnergy
            )

        dissipatedEnergyGeV =
            dissipatedEnergyJ /
            QRTLConstants.joulePerGeV

        dissipatedEnergyTeV =
            dissipatedEnergyGeV /
            1_000.0

        updateEnergyBalance()

        // ============================================================
        // GLOBAL LATTICE MEASUREMENTS
        // ============================================================

        let count =
            Double(
                max(
                    cells.count,
                    1
                )
            )

        averageStrain =
            cells.reduce(0.0) {
                $0 +
                $1.localStrain
            }
            /
            count

        averageTwist =
            cells.reduce(0.0) {
                $0 +
                abs(
                    $1.twist
                )
            }
            /
            count

        // ============================================================
        // ENERGY-WEIGHTED COLLECTIVE AMPLITUDE
        // ============================================================

        var weightedAmplitude =
            0.0

        var weightedEnergy =
            0.0

        for cell in cells {

            let energy =
                max(
                    0.0,
                    cell.localEnergy
                )

            weightedAmplitude +=
                energy *
                cell.amplitude *
                cell.amplitude

            weightedEnergy +=
                energy
        }

        collectiveAmplitude =
            weightedEnergy > 0.0
            ? sqrt(
                weightedAmplitude /
                weightedEnergy
            )
            : 0.0

        peakCollectiveAmplitude =
            max(
                peakCollectiveAmplitude,
                collectiveAmplitude
            )

        // ============================================================
        // COLLECTIVE COHERENCE
        // ============================================================

        calculateCollectiveCoherence()

        // ============================================================
        // COLLISION / PROPAGATION STATE
        // ============================================================

        latticeExcited =
            latticeEnergy >
            QRTLConstants.activeEnergyThresholdJ

        propagationTime =
            max(
                0.0,
                simulationTime -
                collisionTime
            )

        resonanceDevelopment =
            min(
                1.0,
                Double(
                    spectralSampleCount
                )
                /
                Double(
                    max(
                        QRTLConstants.spectralSampleCount,
                        1
                    )
                )
            )

        dampingFraction =
            depositedEnergyJ > 0.0
            ? min(
                1.0,
                dissipatedEnergyJ /
                depositedEnergyJ
            )
            : 0.0

        returnedToEquilibrium =
            latticeEnergy <=
            QRTLConstants.activeEnergyThresholdJ
            &&
            propagationTime > 0.0

        // ============================================================
        // QUARK COLLISION MECHANICS
        // ============================================================

        updateQuarkCollisionState(dt: dt)

        if collisionOccurred {
            let progress = min(1, collisionElapsedTime / quarkVisualDuration)
            if progress < 1 {
                let compression = sin(progress * .pi * 0.5)
                applyQuarkCompression(compression: compression)
                applyTwistAttractionRepulsion(compression: compression, repulsion: 0)
            } else {
                let repulsionProgress = min(1, (collisionElapsedTime - quarkVisualDuration) / quarkVisualDuration)
                let repulsion = sin(repulsionProgress * .pi * 0.5)
                applyQuarkRepulsion(repulsion: repulsion)
                applyTwistAttractionRepulsion(compression: 0, repulsion: repulsion)
                releaseCollisionEnergy(amount: repulsion)
            }
        }

        if returnedToEquilibrium {
            restoreCollisionSymmetry()
        }

        // ============================================================
        // QUARK CONFINEMENT (no ejection)
        //
        // Collision energy no longer escapes the lattice as ejected
        // up-quarks. Instead the quarks stay confined and that
        // energy raises the shell to a higher, more energetic level.
        // Energy stays localized rather than leaking outward, so a
        // stronger collective resonance can develop.
        // ============================================================

        updateBorlagrinoAndCharge(dt: dt)

        if !shellEnergyElevated &&
           depositedEnergyJ > 0.0 {

            let shellEnergyBoost =
                depositedEnergyJ

            energyState.shellEnergy =
                energyState.equilibriumShellEnergy +
                shellEnergyBoost

            let instabilityFromBoost =
                min(
                    1.0,
                    shellEnergyBoost /
                    max(energyState.equilibriumShellEnergy, 1.0e-30)
                )

            energyState.shellInstability =
                max(
                    energyState.shellInstability,
                    instabilityFromBoost
                )

            energyState.deformation =
                energyState.shellInstability

            energyState.isUnstable =
                true

            shellEnergyElevated =
                true
        }

        let shellEnergy = calculateStableShellEnergy()
        _ = shellEnergy

        // ============================================================
        // COLLECTIVE SIGNAL → RESONANT MODE DETECTION
        // ============================================================

        recordCollectiveSignal()

        let naturalFrequency = analyzeNaturalFrequency(
            sampleInterval: dt
        )

        // Persist the measured frequency — evaluateHiggsLikeMode()
        // reads this instance property, not the local return value,
        // so without this assignment it always sees 0 Hz and the
        // frequencyValid gate can never pass.
        naturalFrequencyHz =
            naturalFrequency

        let resonantFrequency = identifyResonantMode(
            naturalFrequency: naturalFrequency
        )

        updateResonancePersistence(
            naturalFrequency: resonantFrequency,
            dt: dt
        )

        let higgsLike = evaluateHiggsLikeMode()
        if higgsLike {
            print("HIGGS-LIKE RESONANT MODE DETECTED")

            // ========================================================
            // TARGET HIT: 125 GeV RESONANT MODE
            //
            // Stop the run loop and surface an alert to the UI.
            // Guarded by `running` so this fires once per detection
            // rather than every remaining frame before stop() takes
            // effect.
            // ========================================================

            if running {
                let massText = String(format: "%.2f", resonantMassGeV)
                let distanceText = String(format: "%.2f", massDistanceFromTarget)

                higgsTargetAlertMessage =
                    "Higgs-like resonant mode detected at \(massText) GeV " +
                    "(target \(QRTLConstants.targetHiggsMassGeV) GeV, " +
                    "Δ\(distanceText) GeV). Simulation stopped."

                higgsTargetReached = true

                stop()
            }
        }
    }
  
    /// Borlagrino flow from kinetic↔potential conversion and twist gradients.
    /// Charge from circulation; does not create energy.
    private func updateBorlagrinoAndCharge(dt: Double) {
        guard collisionOccurred, !cells.isEmpty else {
            averageBorlagrinoMagnitude = 0
            netEmergentCharge = 0
            chargeAsymmetry = 0
            return
        }
        var nextFlow = cells.map { $0.borlagrinoFlow }
        var nextCharge = cells.map { $0.charge }
        let center = SIMD3<Float>(0, 0, 0)

        for i in cells.indices {
            let cell = cells[i]
            // Conversion proxy: potential-like strain vs kinetic-like |v|
            let potProxy = cell.localStrain
            let kinProxy = min(1, Double(simd_length(cell.velocity)) / QRTLConstants.maxLatticeVelocity)
            let conversion = potProxy - kinProxy

            var twistGrad = SIMD3<Float>(0, 0, 0)
            for ni in cell.neighbors {
                let dTwist = Float(cells[ni].twist - cell.twist)
                twistGrad += (cells[ni].position - cell.position) * dTwist
            }
            if !cell.neighbors.isEmpty {
                twistGrad /= Float(cell.neighbors.count)
            }

            var flow = cell.borlagrinoFlow
            flow += twistGrad * Float(QRTLConstants.borlagrinoCoupling * conversion)
            // Circulation bias around collision axis
            let radial = cell.position - center
            let circ = SIMD3<Float>(-radial.y, radial.x, 0) * Float(conversion * 0.05)
            flow += circ
            flow *= Float(1.0 - QRTLConstants.borlagrinoDamping)
            if simd_length(flow) > 2 { flow = simd_normalize(flow) * 2 }
            nextFlow[i] = flow

            // Emergent charge ~ local circulation (finite difference curl proxy)
            var curlZ: Float = 0
            for ni in cell.neighbors {
                let f = cells[ni].borlagrinoFlow
                curlZ += f.y * (cells[ni].position.x - cell.position.x)
                    - f.x * (cells[ni].position.y - cell.position.y)
            }
            let q = Double(curlZ) * QRTLConstants.chargeFromCirculation
            nextCharge[i] = nextCharge[i] * 0.9 + q * 0.1
        }

        for i in cells.indices {
            cells[i].borlagrinoFlow = nextFlow[i]
            cells[i].charge = nextCharge[i]
        }

        let n = Double(max(cells.count, 1))
        averageBorlagrinoMagnitude = cells.reduce(0.0) {
            $0 + Double(simd_length($1.borlagrinoFlow))
        } / n
        netEmergentCharge = cells.reduce(0.0) { $0 + $1.charge }
        let absSum = cells.reduce(0.0) { $0 + abs($1.charge) }
        chargeAsymmetry = absSum > 1e-12 ? abs(netEmergentCharge) / absSum : 0
    }

    private func calculateCollectiveCoherence() {

        var real = 0.0
        var imag = 0.0
        var w = 0.0
        var activeCellCount = 0

        for c in cells {

            let weight = max(c.localEnergy, 0)

            guard weight > QRTLConstants.activeEnergyThresholdJ else {
                continue
            }

            activeCellCount += 1

            real += weight * cos(c.phase)
            imag += weight * sin(c.phase)
            w += weight
        }

        let phaseVectorMagnitude = sqrt(real * real + imag * imag)

        guard w > 0 else {

            collectiveCoherence = 0
            resonantModeEnergyJ = 0
            resonantModeEnergyGeV = 0
            resonantModeEnergyTeV = 0
            resonantModeEnergy = 0

            print("""
            
            ===== COLLECTIVE COHERENCE DEBUG =====
            
            Total cells:
                \(cells.count)
            
            Active cells:
                \(activeCellCount)
            
            Active energy threshold:
                \(QRTLConstants.activeEnergyThresholdJ) J
            
            Real phase component:
                \(real)
            
            Imaginary phase component:
                \(imag)
            
            Phase-vector magnitude:
                \(phaseVectorMagnitude)
            
            Weighted active energy:
                \(w) J
            
            ⚠️ No active energy above threshold.
            
            =======================================
            
            """)

            return
        }

        collectiveCoherence =
            min(1.0, phaseVectorMagnitude / w)

        // Spin-0-like resonance proxy:
        // coherent phase alignment converts lattice energy
        // into the resonant-mode energy estimate.
        resonantModeEnergyJ =
            latticeEnergy *
            collectiveCoherence *
            collectiveCoherence

        resonantModeEnergyGeV =
            resonantModeEnergyJ /
            QRTLConstants.joulePerGeV

        resonantModeEnergyTeV =
            resonantModeEnergyGeV / 1_000.0

        resonantModeEnergy =
            resonantModeEnergyJ

        print("""
        
        ===== COLLECTIVE COHERENCE DEBUG =====
        
        Total cells:
            \(cells.count)
        
        Active cells:
            \(activeCellCount)
        
        Active energy threshold:
            \(QRTLConstants.activeEnergyThresholdJ) J
        
        Lattice energy:
            \(latticeEnergy) J
        
        Real phase component:
            \(real)
        
        Imaginary phase component:
            \(imag)
        
        Phase-vector magnitude:
            \(phaseVectorMagnitude)
        
        Weighted active energy:
            \(w) J
        
        Collective coherence:
            \(collectiveCoherence)
        
        Coherence squared:
            \(collectiveCoherence * collectiveCoherence)
        
        Resonant mode energy:
            \(resonantModeEnergyJ) J
        
        Resonant mode energy:
            \(resonantModeEnergyGeV) GeV
        
        Resonant mode energy:
            \(resonantModeEnergyTeV) TeV
        
        =========================================
        
        """)
    }
    private func recordCollectiveLatticeSignal() {
        guard collisionOccurred, !cells.isEmpty else { return }
        var wd = 0.0, te = 0.0
        for c in cells {
            let e = max(c.localEnergy, 0)
            guard e > 1e-30 else { continue }
            wd += e * c.modeCoordinate
            te += e
        }
        guard te > 1e-30 else { return }
        spectralAnalyzer.append(wd / te)
        spectralSampleCount = spectralAnalyzer.samples.count
        spectralNyquistHz = 0.5 / QRTLConstants.timeStep
        if spectralAnalyzer.samples.count >= min(256, QRTLConstants.spectralSampleCount),
           let spectral = spectralAnalyzer.analyze(sampleInterval: QRTLConstants.timeStep) {
            resonantFrequencyHz = spectral.frequencyHz
            resonantAngularFrequency = spectral.angularFrequency
            resonantWavelengthMeters = spectral.wavelengthMeters
            spectralPeakAmplitude = spectral.peakAmplitude
            spectralAnalysisComplete = true
        }
    }

    private func measureCollectiveMode() {
        var ws = 0.0, wv = 0.0, tw = 0.0
        for c in cells {
            let weight = max(c.localEnergy, 0) + c.amplitude * c.amplitude
            guard weight > QRTLConstants.activeEnergyThresholdJ else { continue }
            ws += c.modeCoordinate * weight
            wv += c.modeVelocity * weight
            tw += weight
        }
        guard tw > 0 else { return }
        let signal = ws / tw
        let vel = wv / tw
        if !phaseReferenceEstablished {
            previousCollectiveSignal = signal
            previousCollectiveVelocity = vel
            phaseReferenceEstablished = true
            return
        }
        let cross = previousCollectiveSignal <= 0 && signal > 0 && vel > 0
        if cross {
            if let prev = lastPositiveCrossingTime {
                let period = simulationTime - prev
                if period > 1e-6, period.isFinite {
                    measuredPeriods.append(period)
                    if measuredPeriods.count > 8 { measuredPeriods.removeFirst() }
                    let avg = measuredPeriods.reduce(0, +) / Double(measuredPeriods.count)
                    if avg > 0 { resonantFrequencyHz = 1.0 / avg }
                }
            }
            lastPositiveCrossingTime = simulationTime
        }
        previousCollectiveSignal = signal
        previousCollectiveVelocity = vel
    }

    private func massFromFrequency(_ f: Double) -> Double {
        guard f.isFinite, f > 0 else { return 0 }
        return (QRTLConstants.planckConstant * f) / QRTLConstants.joulePerGeV
    }

    private func updateHiggsLikeMode(dt: Double) {
        higgsMode.age += dt
        calculateCollectiveCoherence()

        var wa = 0.0, pr = 0.0, pi = 0.0, pw = 0.0
        for c in cells {
            let w = max(c.localEnergy, 0)
            guard w > QRTLConstants.activeEnergyThresholdJ else { continue }
            wa += abs(c.modeCoordinate) * w
            pr += w * cos(c.phase)
            pi += w * sin(c.phase)
            pw += w
        }
        let amp = pw > 0 ? wa / pw : 0
        let coh = pw > 0 ? min(1, sqrt(pr * pr + pi * pi) / pw) : 0

        resonantMassGeV = massFromFrequency(resonantFrequencyHz)
        massDistanceFromTarget = abs(QRTLConstants.targetHiggsMassGeV - resonantMassGeV)
        higgsMode.frequencyHz = resonantFrequencyHz
        higgsMode.massGeV = resonantMassGeV
        higgsMode.energy = resonantModeEnergyJ
        higgsMode.amplitude = amp
        higgsMode.coherence = coh
        higgsMode.shellEnergy = energyState.shellEnergy
        higgsMode.shellInstability = energyState.shellInstability

        // Spin-0-like: high coherence, low charge asymmetry; not a new energy shell
        let spin0Like = coh > 0.5 && chargeAsymmetry < 0.35
        let nearTarget = resonantMassGeV > 0 && massDistanceFromTarget < 50.0
        // nearTarget is optional diagnostic; primary gates:
        let sufficientEnergy = resonantModeEnergyJ > QRTLConstants.activeEnergyThresholdJ
            || latticeEnergy > QRTLConstants.activeEnergyThresholdJ
        let measuredFrequency = resonantFrequencyHz > 0
        let shellWasDestabilized = collisionOccurred &&
            (energyState.shellInstability > 0.01 || collisionEnergyReleased)

        higgsMode.active =
            collisionOccurred &&
            sufficientEnergy &&
            spin0Like &&
            measuredFrequency &&
            shellWasDestabilized

        _ = nearTarget // available for stricter gate if desired

        if higgsMode.active {
            higgsNode.isHidden = false
            let vs = Float(max(0.05, min(2.5, amp * 8)))
            higgsNode.scale = SCNVector3(vs, vs, vs)
            higgsNode.opacity = CGFloat(max(0.15, min(1, coh)))
        } else {
            higgsNode.isHidden = true
        }

        if !energyState.isUnstable && higgsMode.active {
            higgsMode.decayProgress = min(1, higgsMode.decayProgress + dt * 0.15)
            if higgsMode.decayProgress >= 1 {
                higgsMode.active = false
                higgsNode.isHidden = true
            }
        }
    }

