    private func checkEnergyConservation(
        initialEnergy: Double
    ) -> Bool {

        guard initialEnergy > 0.0 else {
            return false
        }

        let ejectedEnergy =
            calculateEjectedParticleEnergy()

        let currentLatticeEnergy =
            totalMechanicalLatticeEnergy()

        let accountedEnergy =
            ejectedEnergy +
            currentLatticeEnergy

        guard accountedEnergy.isFinite else {
            return false
        }

        let difference =
            abs(
                initialEnergy -
                accountedEnergy
            )

        let relativeError =
            difference /
            max(
                abs(initialEnergy),
                1.0e-30
            )

        let tolerance = 0.05

        print("""
        
        ENERGY CONSERVATION
        
        Initial energy:
            \(initialEnergy) J
        
        Ejected energy:
            \(ejectedEnergy) J
        
        Lattice energy:
            \(currentLatticeEnergy) J
        
        Accounted energy:
            \(accountedEnergy) J
        
        Relative error:
            \(relativeError)
        
        """)
        
        return relativeError <= tolerance
    }
    private func calculateStableShellEnergy() -> Double {

        guard !cells.isEmpty else {
            return 0.0
        }

        var shellEnergy = 0.0

        for cell in cells {

            let displacementMagnitude =
                Double(
                    length(cell.displacement)
                )

            let velocityMagnitude =
                Double(
                    length(cell.velocity)
                )

            let twistMagnitude =
                abs(
                    Double(cell.twist)
                )

            let phaseMagnitude =
                abs(
                    Double(cell.phase)
                )

            let displacementEnergy =
                0.5 *
                QRTLConstants.effectiveStiffnessNPerM *
                displacementMagnitude *
                displacementMagnitude

            let kineticEnergy =
                0.5 *
                QRTLConstants.effectiveMassKg *
                velocityMagnitude *
                velocityMagnitude

            let twistEnergy =
                0.5 *
                QRTLConstants.twistStiffness *
                twistMagnitude *
                twistMagnitude

            let phaseEnergy =
                0.5 *
                QRTLConstants.phaseStiffness *
                phaseMagnitude *
                phaseMagnitude

            shellEnergy +=
                displacementEnergy +
                kineticEnergy +
                twistEnergy +
                phaseEnergy
        }

        stableShellEnergyJ =
            max(
                0.0,
                shellEnergy
            )

        return stableShellEnergyJ
    }
    private func calculateEjectedParticleEnergy() -> Double {

        guard !ejectedUpQuarks.isEmpty else {
            return 0.0
        }

        let energy =
            ejectedUpQuarks.reduce(0.0) {
                partialResult,
                particle in

                guard particle.active else {
                    return partialResult
                }

                return partialResult +
                    particle.energyJ
            }

        return energy.isFinite
            ? energy
            : 0.0
    }
    private func updateEjectedUpQuarks(dt: Double) {

        guard dt > 0.0 else {
            return
        }

        guard !ejectedUpQuarks.isEmpty else {
            return
        }

        for index in ejectedUpQuarks.indices {

            guard ejectedUpQuarks[index].active else {
                continue
            }

            let velocity =
                ejectedUpQuarks[index].velocity

            ejectedUpQuarks[index].position +=
                velocity * Float(dt)
        }
    }
    private func createEjectedUpQuarks(
        collisionEnergyJ: Double,
        collisionCenter: SIMD3<Float>
    ) {

        guard collisionEnergyJ > 0.0 else {
            return
        }

        let outgoingEnergyFraction = 0.50

        let totalEjectedEnergy =
            collisionEnergyJ *
            outgoingEnergyFraction

        let energyPerParticle =
            totalEjectedEnergy / 2.0

        let upQuarkMassKg =
            QRTLConstants.upQuarkMassKg

        guard upQuarkMassKg > 0.0 else {
            return
        }

        // Relativistic energy-momentum relation:
        //
        // E² = (pc)² + (mc²)²

        let c =
            QRTLConstants.speedOfLight

        let restEnergy =
            upQuarkMassKg * c * c

        guard energyPerParticle > restEnergy else {
            return
        }

        let momentumMagnitude =
            sqrt(
                max(
                    0.0,
                    energyPerParticle *
                    energyPerParticle -
                    restEnergy *
                    restEnergy
                )
            ) / c

        let totalEnergy =
            energyPerParticle

        let gamma =
            totalEnergy / restEnergy

        let beta =
            sqrt(
                max(
                    0.0,
                    1.0 -
                    1.0 / (gamma * gamma)
                )
            )

        let speed =
            beta * c

        let momentum =
            momentumMagnitude

        let directionA =
            SIMD3<Float>(
                1.0,
                0.0,
                0.0
            )

        let directionB =
            SIMD3<Float>(
                -1.0,
                0.0,
                0.0
            )

        let velocityA =
            directionA *
            Float(speed)

        let velocityB =
            directionB *
            Float(speed)

        let momentumA =
            directionA *
            Float(momentum)
        
        let momentumB =
            directionB *
            Float(momentum)

        let offset: Float = 0.5

        ejectedUpQuarks = [

            EjectedUpQuark(
                position:
                    collisionCenter +
                    SIMD3<Float>(
                        offset,
                        0.0,
                        0.0
                    ),

                velocity:
                    velocityA,

                momentum:
                    momentumA,

                energyJ:
                    energyPerParticle,

                active:
                    true
            ),

            EjectedUpQuark(
                position:
                    collisionCenter +
                    SIMD3<Float>(
                        -offset,
                        0.0,
                        0.0
                    ),

                velocity:
                    velocityB,

                momentum:
                    momentumB,

                energyJ:
                    energyPerParticle,

                active:
                    true
            )
        ]

        ejectedEnergyJ =
            totalEjectedEnergy

        print("""
        
        EJECTED UP QUARKS
        
        Number:
            \(ejectedUpQuarks.count)
        
        Energy per particle:
            \(energyPerParticle) J
        
        Total ejected energy:
            \(ejectedEnergyJ) J
        
        Speed:
            \(speed) m/s
        
        Momentum per particle:
            \(momentum) kg·m/s
        
        """)
    }
