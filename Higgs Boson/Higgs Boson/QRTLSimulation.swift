    private func initializeCollision(
        kineticEnergyJ: Double,
        collisionPosition: Int
    ) {
        // --------------------------------------------------------
        // RESET COLLISION STATE
        // --------------------------------------------------------

        collisionActive = true
        collisionCompleted = false

        collectiveSignal.removeAll(keepingCapacity: true)

        naturalAngularFrequency = 0.0
        naturalFrequencyHz = 0.0

        resonantModeAmplitude = 0.0
        resonantModeEnergy = 0.0

        higgsLikeModeDetected = false
        resonancePersistence = 0.0

        // --------------------------------------------------------
        // STORE COLLISION ENERGY
        // --------------------------------------------------------

        collisionKineticEnergyJ = max(kineticEnergyJ, 0.0)

        // --------------------------------------------------------
        // CLEAR PREVIOUS LATTICE MOTION
        // --------------------------------------------------------

        for index in cells.indices {

            // Fixed lattice position is NOT changed.
            // position is a let constant in QRTLCell.

            cells[index].displacement = .zero
            cells[index].velocity = .zero

            cells[index].twist = 0.0
            cells[index].phase = 0.0
            cells[index].amplitude = 0.0

            cells[index].localEnergy = 0.0
            cells[index].localStrain = 0.0
            cells[index].couplingState = 0.0

            cells[index].modeCoordinate = 0.0
            cells[index].modeVelocity = 0.0
            cells[index].modeAcceleration = 0.0
            cells[index].modeDirection = .zero

            cells[index].previousPhase = 0.0
            cells[index].unwrappedPhase = 0.0

            cells[index].borlagrinoFlow = .zero
            cells[index].charge = 0.0
        }

        // --------------------------------------------------------
        // VALIDATE LATTICE
        // --------------------------------------------------------

        guard !cells.isEmpty else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // COLLISION LOCATION
        // --------------------------------------------------------

        let centerIndex = min(
            max(collisionPosition, 0),
            cells.count - 1
        )

        // --------------------------------------------------------
        // LOCALIZE COLLISION ENERGY
        // --------------------------------------------------------

        let radius = max(
            QRTLConstants.collisionRadius,
            1.0
        )

        var totalWeight = 0.0

        var weights = [Double](
            repeating: 0.0,
            count: cells.count
        )

        let centerX = Double(
            cells[centerIndex].position.x
        )

        let centerY = Double(
            cells[centerIndex].position.y
        )

        for index in cells.indices {

            let dx =
                Double(cells[index].position.x) - centerX

            let dy =
                Double(cells[index].position.y) - centerY

            let distanceSquared =
                dx * dx + dy * dy

            let weight = exp(
                -distanceSquared /
                (2.0 * radius * radius)
            )

            weights[index] = weight
            totalWeight += weight
        }

        guard totalWeight > 0.0 else {
            collisionActive = false
            return
        }

        // --------------------------------------------------------
        // CONVERT COLLISION ENERGY INTO LATTICE DISPLACEMENT
        //
        // E = 1/2 k x²
        //
        // x = sqrt(2E/k)
        // --------------------------------------------------------

        let stiffness = max(
            QRTLConstants.effectiveStiffnessNPerM,
            Double.leastNonzeroMagnitude
        )

        for index in cells.indices {

            let normalizedWeight =
                weights[index] / totalWeight

            let localEnergy =
                collisionKineticEnergyJ * normalizedWeight

            cells[index].localEnergy =
                localEnergy

            let displacementMagnitude =
                sqrt(
                    max(
                        2.0 * localEnergy / stiffness,
                        0.0
                    )
                )

            // Radial collision disturbance.
            let direction: Double =
                index == centerIndex ? 1.0 : 0.5

            let displacement =
                displacementMagnitude * direction

            // Dynamic displacement.
            cells[index].displacement.x =
                Float(displacement)

            // Store amplitude consistently with displacement.
            cells[index].amplitude =
                displacement

            // Local strain.
            cells[index].localStrain =
                displacement /
                max(
                    QRTLConstants.cellSpacing,
                    Double.leastNonzeroMagnitude
                )
        }

        // --------------------------------------------------------
        // INITIAL COLLISION SIGNAL
        // --------------------------------------------------------

        let initialSignal =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        collectiveSignal.append(
            initialSignal
        )

        // --------------------------------------------------------
        // INITIAL MECHANICAL REFERENCE
        //
        // This does not assign the collision wavelength.
        // The propagated collective signal is analyzed later.
        // --------------------------------------------------------

        let mass = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        naturalAngularFrequency =
            sqrt(stiffness / mass)

        naturalFrequencyHz =
            naturalAngularFrequency /
            (2.0 * Double.pi)

        // --------------------------------------------------------
        // DEBUG VALUES
        // --------------------------------------------------------

        let initializedEnergy =
            cells.reduce(0.0) { total, cell in
                total + cell.localEnergy
            }

        let initializedDisplacement =
            cells.reduce(0.0) { total, cell in
                total + Double(
                    simd_length(cell.displacement)
                )
            }

        let centerCell =
            cells[centerIndex]

        /*
        print("""
        
        ========================================================
        COLLISION INITIALIZATION DEBUG
        ========================================================

        Collision kinetic energy:
            \(collisionKineticEnergyJ) J

        Localized lattice energy:
            \(initializedEnergy) J

        Energy ratio:
            \(collisionKineticEnergyJ > 0.0
                ? initializedEnergy / collisionKineticEnergyJ
                : 0.0)

        Total displacement:
            \(initializedDisplacement)

        Initial signal:
            \(initialSignal)

        Center cell:
            \(centerIndex)

        Center displacement:
            \(centerCell.displacement)

        Center local energy:
            \(centerCell.localEnergy)

        Center strain:
            \(centerCell.localStrain)

        Natural angular frequency:
            \(naturalAngularFrequency)

        Natural frequency:
            \(naturalFrequencyHz) Hz

        ========================================================
        """)
         */
        
        evaluateHelium2Candidate()
    }

    private func updateQuarkCollisionState(dt: Double) {
        guard collisionOccurred else { return }
        let progress = min(1, collisionElapsedTime / quarkVisualDuration)
        if progress < 1 {
            let compression = sin(progress * .pi * 0.5)
            for i in protonAQuarks.indices {
                protonAQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonAQuarks[i].position.x
                protonAQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            for i in protonBQuarks.indices {
                protonBQuarks[i].compression = compression
                let targetX = 0.0
                let cx = protonBQuarks[i].position.x
                protonBQuarks[i].position.x = cx + (targetX - cx) * compression * 0.05
            }
            return
        }
        let repulsionProgress = min(1, (collisionElapsedTime - quarkVisualDuration) / quarkVisualDuration)
        let repulsion = sin(repulsionProgress * .pi * 0.5)
        for i in protonAQuarks.indices {
            let o = protonAQuarks[i].originalPosition
            protonAQuarks[i].position.x = o.x - repulsion * 1.5
            protonAQuarks[i].velocity.x = -repulsion
        }
        for i in protonBQuarks.indices {
            let o = protonBQuarks[i].originalPosition
            protonBQuarks[i].position.x = o.x + repulsion * 1.5
            protonBQuarks[i].velocity.x = repulsion
        }
        if repulsionProgress >= 1 { quarksSeparated = true }
    }

    private func applyQuarkCompression(compression: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = compression * influence
            cells[i].localStrain = min(1, cells[i].localStrain + f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.05)
            cells[i].twist += f * QRTLConstants.twistAttractStrength
        }
        // Shell tracks full collision budget; instability follows compression
        energyState.shellInstability = max(energyState.shellInstability, compression)
        energyState.shellEnergy = QRTLConstants.collisionKineticEnergyJ
    }

    private func applyQuarkRepulsion(repulsion: Double) {
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            guard dx <= collisionCoreRadius else { continue }
            let influence = max(0, 1 - dx / collisionCoreRadius)
            let f = repulsion * influence
            cells[i].localStrain = max(0, cells[i].localStrain - f * 0.1)
            cells[i].amplitude = min(1, cells[i].amplitude + f * 0.1)
            cells[i].twist -= f * QRTLConstants.twistRepelStrength
        }
    }


    private func applyTwistAttractionRepulsion(
        compression: Double,
        repulsion: Double
    ) {

        let centerX =
            (protonAX + protonBX) * 0.5

        guard centerX.isFinite,
              collisionCoreRadius.isFinite,
              collisionCoreRadius > 0.0 else {
            return
        }

        for i in cells.indices {

            let cellX =
                Double(cells[i].position.x)

            guard cellX.isFinite else {
                continue
            }

            let dx =
                abs(cellX - centerX)

            guard dx <= collisionCoreRadius else {
                continue
            }

            let influence =
                max(
                    0.0,
                    1.0 - dx / collisionCoreRadius
                )

            let attract =
                compression *
                influence *
                QRTLConstants.twistAttractStrength

            let repel =
                repulsion *
                influence *
                QRTLConstants.twistRepelStrength

            let twistDelta =
                attract - repel

            guard twistDelta.isFinite else {
                continue
            }

            // Twist is a dimensionless QRTL state.
            // It does NOT directly inject velocity or energy.
            cells[i].twist += twistDelta

            if !cells[i].twist.isFinite {
                cells[i].twist = 0.0
            }
        }
    }


    private func releaseCollisionEnergy(amount: Double) {
        guard !cells.isEmpty else { return }
        let release = collisionCoreEnergyJ * amount * 0.001
        collisionReleasedEnergyJ += release
        let centerX = (protonAX + protonBX) * 0.5
        for i in cells.indices {
            let dx = abs(Double(cells[i].position.x) - centerX)
            let influence = exp(-(dx * dx) / (collisionCoreRadius * collisionCoreRadius))
            cells[i].amplitude = min(1, cells[i].amplitude + influence * amount * 0.02)
        }
    }

    private func restoreCollisionSymmetry() {
        energyState.shellInstability = 0
        energyState.isUnstable = false
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        collisionEnergySymmetry = 1
        collisionMassEnergyJ = 0
        collisionMassEquivalentKg = 0
        collisionCoreEnergyJ = 0
    }

    private func updateShellState(dt: Double) {
        guard energyState.isUnstable else { return }
        let rate = dt / shellRelaxationVisualSeconds
        energyState.shellInstability = max(0, energyState.shellInstability - rate)
        energyState.deformation = energyState.shellInstability
        energyState.shellEnergy = energyState.equilibriumShellEnergy
        if energyState.shellInstability < 0.05 {
            energyState.isUnstable = false
        }
        let s = Float(1 + energyState.shellInstability * 0.9)
        protonAShellNode.scale = SCNVector3(s, s, s)
        protonBShellNode.scale = SCNVector3(s, s, s)
    }

    private func updateEnergyShell() {

        guard collisionKineticEnergyJ.isFinite,
              collisionKineticEnergyJ > 0.0,
              shellActive else {
            return
        }
        
        print("""
         🔥🔥🔥 updateEnergyShell CALLED
         collisionKineticEnergyJ = \(collisionKineticEnergyJ)
         shellActive = \(shellActive)
         shellFormationTime = \(shellFormationTime)
         shellEnergyReleased = \(shellEnergyReleased)
         shellStoredEnergyJ = \(shellStoredEnergyJ)
         cells = \(cells.count)
         """)

        let physicsDt = QRTLConstants.timeStep

        guard physicsDt.isFinite,
              physicsDt > 0.0 else {
            return
        }

        // ============================================================
        // SHELL FORMATION
        // ============================================================

        if shellFormationTime <= 0.0 {

            shellPhase = .forming
            shellEnergyReleased = false

            // Store the incoming collision energy in the shell.
            shellStoredEnergyJ = collisionKineticEnergyJ

        }

        // ============================================================
        // ADVANCE PHYSICAL SHELL TIME
        // ============================================================

        shellFormationTime += physicsDt

        let formationDuration = max(
            QRTLConstants.timeStep * 5.0,
            1.0e-3
        )

        // ============================================================
        // SHELL FORMING
        // ============================================================

        if shellFormationTime < formationDuration {

            shellPhase = .forming
            shellEnergyReleased = false

            return
        }

        // ============================================================
        // SHELL COMPRESSED / STORED ENERGY
        // ============================================================

        if shellFormationTime < formationDuration * 2.0 {

            shellPhase = .compressed
            shellEnergyReleased = false

            return
        }

        // ============================================================
        // PREVENT DOUBLE RELEASE
        // ============================================================

        guard !shellEnergyReleased else {

            shellPhase = .released

            return
        }

        // ============================================================
        // ENERGY AVAILABLE FOR RELEASE
        // ============================================================

        let releasedEnergyJ = shellStoredEnergyJ

        guard releasedEnergyJ.isFinite,
              releasedEnergyJ > 0.0 else {
            return
        }

        // ============================================================
        // FIND COLLISION-ACTIVE CELLS
        // ============================================================

        let activeIndices = cells.indices.filter {
            cells[$0].localEnergy >
                QRTLConstants.activeEnergyThreshold
        }

        guard !activeIndices.isEmpty else {
            return
        }

        // ============================================================
        // ENERGY PER ACTIVE CELL
        // ============================================================

        let energyPerCell =
            releasedEnergyJ /
            Double(activeIndices.count)

        guard energyPerCell.isFinite,
              energyPerCell > 0.0 else {
            return
        }

        // ============================================================
        // EFFECTIVE CELL MASS
        // ============================================================

        let cellMassKg = max(
            QRTLConstants.effectiveMassKg,
            Double.leastNonzeroMagnitude
        )

        // ============================================================
        // SHELL ENERGY → KINETIC VELOCITY
        //
        // E = 1/2 m v²
        //
        // v = sqrt(2E/m)
        // ============================================================

        let velocityMagnitude = sqrt(
            2.0 *
            energyPerCell /
            cellMassKg
        )

        guard velocityMagnitude.isFinite,
              velocityMagnitude > 0.0 else {
            return
        }

        // ============================================================
        // DISTRIBUTE SHELL ENERGY INTO LATTICE MOTION
        // ============================================================

        var injectedKineticEnergyJ = 0.0

        for index in activeIndices {

            // --------------------------------------------------------
            // MODE DIRECTION
            // --------------------------------------------------------

            let direction = SIMD3<Double>(
                Double(cells[index].modeDirection.x),
                Double(cells[index].modeDirection.y),
                Double(cells[index].modeDirection.z)
            )

            let directionLength = simd_length(direction)

            let normalizedDirection =
                directionLength > 0.0
                ? direction / directionLength
                : SIMD3<Double>(1.0, 0.0, 0.0)

            // --------------------------------------------------------
            // INJECT VELOCITY
            // --------------------------------------------------------

            let velocity =
                normalizedDirection *
                velocityMagnitude

            cells[index].velocity =
                SIMD3<Float>(
                    Float(velocity.x),
                    Float(velocity.y),
                    Float(velocity.z)
                )

            // --------------------------------------------------------
            // UPDATE MODE STATE
            // --------------------------------------------------------

            let displacement = SIMD3<Double>(
                Double(cells[index].displacement.x),
                Double(cells[index].displacement.y),
                Double(cells[index].displacement.z)
            )

            let modeCoordinate =
                simd_dot(
                    displacement,
                    normalizedDirection
                )

            let modeVelocity =
                simd_dot(
                    velocity,
                    normalizedDirection
                )

            let omega = sqrt(
                QRTLConstants.effectiveStiffnessNPerM /
                cellMassKg
            )

            guard omega.isFinite,
                  omega > 0.0 else {
                continue
            }

            cells[index].modeCoordinate =
                modeCoordinate

            cells[index].modeVelocity =
                modeVelocity

            cells[index].modeAcceleration =
                -omega * omega * modeCoordinate

            // --------------------------------------------------------
            // PHASE
            // --------------------------------------------------------

            cells[index].previousPhase =
                cells[index].phase

            cells[index].phase =
                atan2(
                    modeVelocity,
                    omega * modeCoordinate
                )

            // --------------------------------------------------------
            // AMPLITUDE
            // --------------------------------------------------------

            let amplitudeSquared =
                modeCoordinate * modeCoordinate +
                pow(modeVelocity / omega, 2.0)

            cells[index].amplitude =
                sqrt(
                    max(
                        0.0,
                        amplitudeSquared
                    )
                )

            // --------------------------------------------------------
            // MECHANICAL ENERGY
            // --------------------------------------------------------

            let potentialEnergy =
                0.5 *
                QRTLConstants.effectiveStiffnessNPerM *
                simd_length_squared(displacement)

            let kineticEnergy =
                0.5 *
                cellMassKg *
                simd_length_squared(velocity)

            let totalCellEnergy =
                potentialEnergy +
                kineticEnergy

            cells[index].localEnergy =
                max(
                    0.0,
                    totalCellEnergy
                )

            injectedKineticEnergyJ +=
                kineticEnergy
        }

        // ============================================================
        // VERIFY ENERGY TRANSFER
        // ============================================================

        let transferErrorJ =
            injectedKineticEnergyJ -
            releasedEnergyJ

        let transferErrorFraction =
            releasedEnergyJ > 0.0
            ? abs(transferErrorJ) / releasedEnergyJ
            : 0.0

        // ============================================================
        // TRANSFER OWNERSHIP
        // ============================================================

        shellEnergyReleased = true
        shellPhase = .released

        // Shell no longer owns the released energy.
        shellStoredEnergyJ = 0.0
      updateEnergyShellVisual()
        updateEnergyShellPulse()
        print("""
        ============================================================
        ENERGY LOCATION — BEFORE SHELL UPDATE
        ============================================================

        ENERGY SHELL
            Shell stored energy:
                \(shellStoredEnergyJ) J
            Shell stored energy:
                \(shellStoredEnergyJ / QRTLConstants.joulesPerGeV) GeV
            Shell active:
                \(shellActive)
            Shell released:
                \(shellEnergyReleased)

        LATTICE
            Total lattice energy:
                \(cells.reduce(0.0) { $0 + $1.localEnergy }) J
            Total lattice energy:
                \(cells.reduce(0.0) { $0 + $1.localEnergy } /
                  QRTLConstants.joulesPerGeV) GeV
            Active cells:
                \(cells.filter {
                    $0.localEnergy >= QRTLConstants.activeEnergyThreshold
                }.count)

        ENERGY ACCOUNTING
            Collision energy:
                \(collisionKineticEnergyJ) J
            Collision energy:
                \(collisionKineticEnergyJ /
                  QRTLConstants.joulesPerGeV) GeV

        ============================================================
        """)
    }
    private func releaseShellEnergyIntoLattice() {

        // ============================================================
        // RUN ONCE ONLY
        // ============================================================

        guard !shellEnergyReleased else {
            return
        }

        guard !cells.isEmpty else {
            return
        }

        // ============================================================
        // ORIGINAL COLLISION ENERGY = ONLY ENERGY SOURCE
        // ============================================================

        guard collisionKineticEnergyJ.isFinite,
              collisionKineticEnergyJ > 0.0 else {
            return
        }

        let collisionBudgetJ =
            collisionKineticEnergyJ

        // ============================================================
        // SHELL MUST CONTAIN THE COLLISION BUDGET
        // ============================================================

        shellStoredEnergyJ =
            collisionBudgetJ

        // ============================================================
        // 100% OF THE COLLISION BUDGET LEAVES THE SHELL
        // ============================================================

        let energyToReleaseJ =
            shellStoredEnergyJ

        guard energyToReleaseJ.isFinite,
              energyToReleaseJ > 0.0 else {
            return
        }

        // ============================================================
        // COLLISION CENTER
        // ============================================================

        let center =
            SIMD3<Double>(
                0.0,
                0.0,
                0.0
            )

        let radius =
            max(
                Double(QRTLConstants.latticeSize) / 4.0,
                1.0
            )

        // ============================================================
        // FIND AFFECTED CELLS
        // ============================================================

        var affectedIndices: [Int] = []

        for index in cells.indices {

            let position =
                SIMD3<Double>(
                    Double(cells[index].position.x),
                    Double(cells[index].position.y),
                    Double(cells[index].position.z)
                )

            let distance =
                simd_distance(
                    position,
                    center
                )

            if distance <= radius {
                affectedIndices.append(index)
            }
        }

        // ============================================================
        // FALLBACK TO CLOSEST CELL
        // ============================================================

        if affectedIndices.isEmpty {

            if let centerIndex =
                cells.indices.min(by: {

                    let p0 =
                        SIMD3<Double>(
                            Double(cells[$0].position.x),
                            Double(cells[$0].position.y),
                            Double(cells[$0].position.z)
                        )

                    let p1 =
                        SIMD3<Double>(
                            Double(cells[$1].position.x),
                            Double(cells[$1].position.y),
                            Double(cells[$1].position.z)
                        )

                    return simd_distance(p0, center) <
                        simd_distance(p1, center)
                })
            {
                affectedIndices =
                    [centerIndex]
            }
        }

        guard !affectedIndices.isEmpty else {
            return
        }

        // ============================================================
        // EFFECTIVE CELL MASS
        // ============================================================

        let cellMassKg =
            max(
                QRTLConstants.effectiveMassKg,
                Double.leastNonzeroMagnitude
            )

        guard cellMassKg.isFinite,
              cellMassKg > 0.0 else {
            return
        }

        // ============================================================
        // CLEAR PRIOR MECHANICAL STATE IN THE IMPACT REGION
        // ============================================================

        for index in affectedIndices {

            cells[index].velocity =
                SIMD3<Float>(repeating: 0.0)

            cells[index].displacement =
                SIMD3<Float>(repeating: 0.0)

            cells[index].modeCoordinate =
                0.0

            cells[index].modeVelocity =
                0.0

            cells[index].modeAcceleration =
                0.0

            cells[index].amplitude =
                0.0

            cells[index].localEnergy =
                0.0
        }

        // ============================================================
        // CALCULATE SPATIAL WEIGHTS
        //
        // The sum of all weights is normalized to 1.0, so the intended
        // injection energy is exactly the collision budget before Float
        // storage and later integration effects are considered.
        // ============================================================

        var weights =
            Array(
                repeating: 0.0,
                count: affectedIndices.count
            )

        var totalWeight =
            0.0

        for i in affectedIndices.indices {

            let index =
                affectedIndices[i]

            let position =
                SIMD3<Double>(
                    Double(cells[index].position.x),
                    Double(cells[index].position.y),
                    Double(cells[index].position.z)
                )

            let distance =
                simd_distance(
                    position,
                    center
                )

            let normalizedDistance =
                min(
                    1.0,
                    distance / radius
                )

            let weight =
                max(
                    0.0,
                    1.0 - normalizedDistance
                )

            weights[i] =
                weight

            totalWeight +=
                weight
        }

        guard totalWeight.isFinite,
              totalWeight > 0.0 else {
            return
        }

        // ============================================================
        // INITIAL ENERGY INJECTION
        //
        // At injection time:
        //
        //     displacement = 0
        //
        // so all injected mechanical energy is kinetic:
        //
        //     E = 1/2 m v²
        // ============================================================

        for i in affectedIndices.indices {

            let index =
                affectedIndices[i]

            let energyFraction =
                weights[i] /
                totalWeight

            let cellEnergyJ =
                collisionBudgetJ *
                energyFraction

            guard cellEnergyJ.isFinite,
                  cellEnergyJ >= 0.0 else {
                continue
            }

            // ========================================================
            // RADIAL DIRECTION
            // ========================================================

            let position =
                SIMD3<Double>(
                    Double(cells[index].position.x),
                    Double(cells[index].position.y),
                    Double(cells[index].position.z)
                )

            let radialDirection =
                position - center

            let distance =
                simd_length(radialDirection)

            let direction =
                distance > 1.0e-12
                ? radialDirection / distance
                : SIMD3<Double>(
                    1.0,
                    0.0,
                    0.0
                )

            // ========================================================
            // VELOCITY FOR THIS CELL'S ALLOCATED ENERGY
            // ========================================================

            let velocityMagnitude =
                sqrt(
                    max(
                        0.0,
                        2.0 *
                        cellEnergyJ /
                        cellMassKg
                    )
                )

            guard velocityMagnitude.isFinite else {
                return
            }

            let velocity =
                direction *
                velocityMagnitude

            // ========================================================
            // STORE INITIAL KINETIC STATE
            // ========================================================

            cells[index].velocity =
                SIMD3<Float>(
                    Float(velocity.x),
                    Float(velocity.y),
                    Float(velocity.z)
                )

            cells[index].displacement =
                SIMD3<Float>(
                    repeating: 0.0
                )

            // ========================================================
            // MODAL STATE
            // ========================================================

            cells[index].modeCoordinate =
                0.0

            cells[index].modeVelocity =
                simd_length(
                    SIMD3<Double>(
                        Double(cells[index].velocity.x),
                        Double(cells[index].velocity.y),
                        Double(cells[index].velocity.z)
                    )
                )

            cells[index].modeAcceleration =
                0.0

            cells[index].amplitude =
                0.0

            cells[index].previousPhase =
                cells[index].phase

            cells[index].phase =
                0.0
        }

        // ============================================================
        // MEASURE ACTUAL LATTICE ENERGY
        //
        // This should ideally measure the same affected region that
        // received the collision impulse. Do not use all cells here if
        // your lattice may already contain unrelated wave energy.
        // ============================================================

        func affectedMechanicalEnergy() -> Double {

            var totalEnergyJ =
                0.0

            for index in affectedIndices {

                let energy =
                    physicalEnergy(
                        displacement:
                            cells[index].displacement,
                        velocity:
                            cells[index].velocity
                    )

                if energy.isFinite,
                   energy >= 0.0 {
                    totalEnergyJ += energy
                }
            }

            return totalEnergyJ
        }

        var measuredEnergyBeforeNormalization =
            affectedMechanicalEnergy()

        guard measuredEnergyBeforeNormalization.isFinite,
              measuredEnergyBeforeNormalization >= 0.0 else {
            return
        }

        // ============================================================
        // DOWN-ONLY ENERGY NORMALIZATION
        //
        // Never create energy.
        //
        // If Float storage, existing integration behavior, or another
        // numerical effect makes injected lattice energy exceed the
        // original collision budget, reduce the state proportionally.
        //
        // Scale both velocity and displacement because:
        //
        //     Kinetic energy   ∝ velocity²
        //     Potential energy ∝ displacement²
        //
        // If measured energy is lower than the budget, leave it lower.
        // ============================================================

        if measuredEnergyBeforeNormalization > collisionBudgetJ {

            let stateScale =
                sqrt(
                    collisionBudgetJ /
                    measuredEnergyBeforeNormalization
                )

            guard stateScale.isFinite,
                  stateScale > 0.0,
                  stateScale < 1.0 else {
                return
            }

            for index in affectedIndices {

                cells[index].velocity *=
                    Float(stateScale)

                cells[index].displacement *=
                    Float(stateScale)

                let energy =
                    physicalEnergy(
                        displacement:
                            cells[index].displacement,
                        velocity:
                            cells[index].velocity
                    )

                cells[index].localEnergy =
                    energy.isFinite && energy >= 0.0
                    ? energy
                    : 0.0
            }

            measuredEnergyBeforeNormalization =
                affectedMechanicalEnergy()

            guard measuredEnergyBeforeNormalization.isFinite,
                  measuredEnergyBeforeNormalization >= 0.0 else {
                return
            }
        }

        // ============================================================
        // RECALCULATE ALL AFFECTED CELL ENERGIES
        //
        // This is required even when no down-normalization occurred.
        // ============================================================

        for index in affectedIndices {

            let energy =
                physicalEnergy(
                    displacement:
                        cells[index].displacement,
                    velocity:
                        cells[index].velocity
                )

            cells[index].localEnergy =
                energy.isFinite && energy >= 0.0
                ? energy
                : 0.0
        }

        // ============================================================
        // FINAL LATTICE ENERGY
        // ============================================================

        let finalLatticeEnergyJ =
            affectedMechanicalEnergy()

        guard finalLatticeEnergyJ.isFinite,
              finalLatticeEnergyJ >= 0.0 else {
            return
        }

        latticeEnergy =
            finalLatticeEnergyJ

        currentLatticeEnergyJ =
            finalLatticeEnergyJ

        currentLatticeEnergyGeV =
            finalLatticeEnergyJ /
            QRTLConstants.joulesPerGeV

        currentLatticeEnergyTeV =
            currentLatticeEnergyGeV /
            1_000.0

        // ============================================================
        // SHELL → LATTICE TRANSFER COMPLETE
        // ============================================================

        shellStoredEnergyJ =
            0.0

        shellEnergyReleased =
            true

        shellActive =
            false

        shellPhase =
            .released

        latticeExcited =
            true

        collisionImpulseApplied =
            true

        // ============================================================
        // DIAGNOSTICS
        // ============================================================

        let energyRatio =
            collisionBudgetJ > 0.0
            ? finalLatticeEnergyJ / collisionBudgetJ
            : 0.0

        let relativeError =
            collisionBudgetJ > 0.0
            ? abs(
                finalLatticeEnergyJ -
                collisionBudgetJ
              ) / collisionBudgetJ
            : 0.0

        let peakCellEnergyJ =
            affectedIndices
                .map {
                    cells[$0].localEnergy
                }
                .max() ?? 0.0

        print("""
        ============================================================
        QRTL SHELL → LATTICE ENERGY TRANSFER
        ============================================================
        Collision budget:
            \(collisionBudgetJ) J

        Collision budget:
            \(collisionBudgetJ / QRTLConstants.joulesPerGeV) GeV

        Shell released:
            \(energyToReleaseJ) J

        Final lattice energy:
            \(finalLatticeEnergyJ) J

        Final lattice energy:
            \(currentLatticeEnergyGeV) GeV

        Final lattice energy:
            \(currentLatticeEnergyTeV) TeV

        Energy ratio:
            \(energyRatio)

        Relative error:
            \(relativeError)

        Affected cells:
            \(affectedIndices.count)

        Peak cell energy:
            \(peakCellEnergyJ) J

        Shell remaining:
            \(shellStoredEnergyJ) J

        Shell released:
            \(shellEnergyReleased)

        Shell active:
            \(shellActive)

        Lattice excited:
            \(latticeExcited)

        Collision impulse applied:
            \(collisionImpulseApplied)
        ============================================================
        """)
    }
   
   


    /// SI mechanical energy. displacement in meters, velocity in m/s.
    /// Do NOT multiply by latticeCellSpacingMeters here.
    /// SI mechanical energy.
    /// displacement: meters, velocity: m/s
    /// Do NOT multiply by latticeCellSpacingMeters.
    private func physicalEnergy(
        displacement: SIMD3<Float>,
        velocity: SIMD3<Float>
    ) -> Double {
        let mass = QRTLConstants.effectiveMassKg
        let stiffness = QRTLConstants.effectiveStiffnessNPerM

        guard mass.isFinite, mass > 0,
              stiffness.isFinite, stiffness > 0,
              displacement.x.isFinite, displacement.y.isFinite, displacement.z.isFinite,
              velocity.x.isFinite, velocity.y.isFinite, velocity.z.isFinite
        else {
            return 0.0
        }

        let x2 =
            Double(displacement.x) * Double(displacement.x) +
            Double(displacement.y) * Double(displacement.y) +
            Double(displacement.z) * Double(displacement.z)

        let v2 =
            Double(velocity.x) * Double(velocity.x) +
            Double(velocity.y) * Double(velocity.y) +
            Double(velocity.z) * Double(velocity.z)

        guard x2.isFinite, x2 >= 0, v2.isFinite, v2 >= 0 else {
            return 0.0
        }

        let potential = 0.5 * stiffness * x2
        let kinetic   = 0.5 * mass * v2
        let total = potential + kinetic

        return (total.isFinite && total >= 0) ? total : 0.0
    }

    func totalMechanicalLatticeEnergy() -> Double {
        cells.reduce(0.0) { partial, cell in
            partial + physicalEnergy(
                displacement: cell.displacement,
                velocity: cell.velocity
            )
        }
    }

    private func updateLattice(dt: Double) {

        guard !cells.isEmpty else {
            return
        }

        // Evolution owner is updateCollisionDynamics only.
        // This function: sync energy, phase/amplitude diagnostics, budget guard.

        guard collisionActive else {
            return
        }

        let physicsDt = QRTLConstants.timeStep
        guard physicsDt.isFinite, physicsDt > 0 else {
            return
        }

        // ------------------------------------------------------------
        // 1) Sync localEnergy from current physical state
        // ------------------------------------------------------------
        for index in cells.indices {

            var cell = cells[index]

            // Finite recovery only (no energy clamp)
            if !cell.displacement.x.isFinite ||
               !cell.displacement.y.isFinite ||
               !cell.displacement.z.isFinite {
                cell.displacement = .zero
            }

            if !cell.velocity.x.isFinite ||
               !cell.velocity.y.isFinite ||
               !cell.velocity.z.isFinite {
                cell.velocity = .zero
            }

            // Authoritative energy from (x, v). Never invent energy here.
            let energy = physicalEnergy(
                displacement: cell.displacement,
                velocity: cell.velocity
            )

            // If energy is invalid, clear state consistently.
            // Do NOT zero velocity while leaving a stale nonzero localEnergy,
            // and do NOT zero localEnergy while leaving a large velocity.
            if energy.isFinite, energy >= 0 {
                cell.localEnergy = energy
            } else {
                cell.displacement = .zero
                cell.velocity = .zero
                cell.localEnergy = 0
            }

            // Phase diagnostic (does not affect energy)
            if !cell.phase.isFinite {
                cell.phase = 0
            }

            let omega = naturalAngularFrequency.isFinite ? naturalAngularFrequency : 0.0
            let phaseIncrement = omega * physicsDt
            if phaseIncrement.isFinite {
                cell.phase += phaseIncrement
            }
            if !cell.phase.isFinite {
                cell.phase = 0
            }
            cell.phase = cell.phase.truncatingRemainder(dividingBy: 2.0 * Double.pi)
            if !cell.phase.isFinite {
                cell.phase = 0
            }

            let amp = simd_length(cell.displacement)
            cell.amplitude = amp.isFinite ? Double(amp) : 0

            let modeV = simd_length(
                SIMD3<Double>(
                    Double(cell.velocity.x),
                    Double(cell.velocity.y),
                    Double(cell.velocity.z)
                )
            )
            cell.modeVelocity = modeV.isFinite ? modeV : 0

            cells[index] = cell
        }

        // ------------------------------------------------------------
        // 2) Budget guard — scale DOWN only (never create energy)
        // ------------------------------------------------------------
        var totalLatticeEnergy = cells.reduce(0.0) { partial, cell in
            let e = cell.localEnergy
            return partial + (e.isFinite && e >= 0 ? e : 0)
        }

        if collisionKineticEnergyJ.isFinite,
           collisionKineticEnergyJ > 0,
           totalLatticeEnergy.isFinite,
           totalLatticeEnergy > collisionKineticEnergyJ * 1.001 {

            let scale = sqrt(collisionKineticEnergyJ / totalLatticeEnergy)

            if scale.isFinite, scale > 0, scale <= 1.0 {
                for index in cells.indices {
                    cells[index].velocity *= Float(scale)
                    cells[index].displacement *= Float(scale)

                    let e = physicalEnergy(
                        displacement: cells[index].displacement,
                        velocity: cells[index].velocity
                    )
                    cells[index].localEnergy = e.isFinite && e >= 0 ? e : 0
                }

                totalLatticeEnergy = cells.reduce(0.0) { partial, cell in
                    let e = cell.localEnergy
                    return partial + (e.isFinite && e >= 0 ? e : 0)
                }
            }
        }

        latticeEnergy = totalLatticeEnergy.isFinite ? totalLatticeEnergy : 0

        // ------------------------------------------------------------
        // 3) Accounting
        // ------------------------------------------------------------
        let accounted = latticeEnergy + ejectedEnergyJ
        if accounted.isFinite, collisionKineticEnergyJ.isFinite {
            dissipatedEnergyJ = max(0, collisionKineticEnergyJ - accounted)
        } else {
            dissipatedEnergyJ = 0
        }

        if collisionKineticEnergyJ > 0, latticeEnergy.isFinite {
            let ratio = latticeEnergy / collisionKineticEnergyJ
            let relErr = abs(latticeEnergy - collisionKineticEnergyJ) / collisionKineticEnergyJ
            print("""
            ------------------------------------------------------------
            QRTL LATTICE ENERGY
            Collision:   \(collisionKineticEnergyJ) J
            Lattice:     \(latticeEnergy) J
            Ejected:     \(ejectedEnergyJ) J
            Unaccounted: \(dissipatedEnergyJ) J
            Ratio:       \(ratio)
            Rel error:   \(relErr)
            shellReleased: \(shellEnergyReleased)
            ------------------------------------------------------------
            """)
        }

        // ------------------------------------------------------------
        // 4) Collective signal buffer
        // ------------------------------------------------------------
        let signal = cells.reduce(0.0) { partial, cell in
            guard cell.amplitude.isFinite, cell.phase.isFinite else {
                return partial
            }
            return partial + cell.amplitude * cos(cell.phase)
        }
        collectiveSignal.append(signal.isFinite ? signal : 0)

        let maxSamples = QRTLConstants.spectralSampleCount
        if collectiveSignal.count > maxSamples {
            collectiveSignal.removeFirst(collectiveSignal.count - maxSamples)
        }
    }

    private func updateBorlagrinoAndCharge(dt: Double) {

        guard collisionOccurred, !cells.isEmpty else {
            averageBorlagrinoMagnitude = 0.0
            netEmergentCharge = 0.0
            chargeAsymmetry = 0.0
            return
        }

        let safeDt = dt.isFinite && dt > 0.0
            ? dt
            : QRTLConstants.timeStep

        guard safeDt.isFinite, safeDt > 0.0 else {
            return
        }

        var nextFlow = cells.map { $0.borlagrinoFlow }
        var nextCharge = cells.map { $0.charge }

        let center = SIMD3<Float>(0, 0, 0)

        // ------------------------------------------------------------
        // COLLISION ENERGY SCALE
        //
        // Used only to create a dimensionless kinetic proxy.
        // Borlagrino flow does NOT create or destroy physical energy.
        // ------------------------------------------------------------

        let referenceEnergyJ = max(
            collisionKineticEnergyJ,
            QRTLConstants.higgsReferenceEnergyJ
        )

        // ------------------------------------------------------------
        // UPDATE LOCAL BORLAGRINO FLOW
        // ------------------------------------------------------------

        for i in cells.indices {

            let cell = cells[i]

            // --------------------------------------------------------
            // POTENTIAL-LIKE PROXY
            //
            // Strain is already dimensionless.
            // --------------------------------------------------------

            let potProxy = cell.localStrain.isFinite
                ? max(0.0, cell.localStrain)
                : 0.0

            // --------------------------------------------------------
            // KINETIC-LIKE PROXY
            //
            // cell.velocity is physical m/s.
            //
            // Convert velocity to kinetic energy:
            //
            //     E = 1/2 m v²
            //
            // Then normalize by the collision/reference energy.
            //
            // This replaces the old:
            //
            //     velocity / maxLatticeVelocity
            //
            // which depended on an artificial velocity clamp.
            // --------------------------------------------------------

            let velocity = SIMD3<Double>(
                Double(cell.velocity.x),
                Double(cell.velocity.y),
                Double(cell.velocity.z)
            )

            let velocitySquared = simd_length_squared(velocity)

            let kineticEnergyJ: Double

            if velocitySquared.isFinite,
               velocitySquared >= 0.0 {

                kineticEnergyJ =
                    0.5 *
                    QRTLConstants.effectiveMassKg *
                    velocitySquared

            } else {
                kineticEnergyJ = 0.0
            }

            let kinProxy: Double

            if referenceEnergyJ.isFinite,
               referenceEnergyJ > 0.0,
               kineticEnergyJ.isFinite {

                kinProxy = min(
                    1.0,
                    max(0.0, kineticEnergyJ / referenceEnergyJ)
                )

            } else {
                kinProxy = 0.0
            }

            // --------------------------------------------------------
            // STRAIN / KINETIC CONVERSION
            // --------------------------------------------------------

            let conversion = potProxy - kinProxy

            // --------------------------------------------------------
            // TWIST GRADIENT
            // --------------------------------------------------------

            var twistGrad = SIMD3<Float>(0, 0, 0)

            for ni in cell.neighbors {

                guard cells.indices.contains(ni) else {
                    continue
                }

                let dTwist = Float(
                    cells[ni].twist - cell.twist
                )

                let positionDelta =
                    cells[ni].position - cell.position

                twistGrad += positionDelta * dTwist
            }

            if !cell.neighbors.isEmpty {
                twistGrad /= Float(cell.neighbors.count)
            }

            // --------------------------------------------------------
            // BORLAGRINO FLOW
            // --------------------------------------------------------

            var flow = cell.borlagrinoFlow

            let coupling =
                QRTLConstants.borlagrinoCoupling * conversion

            if coupling.isFinite {
                flow += twistGrad * Float(coupling)
            }

            // --------------------------------------------------------
            // CIRCULATION BIAS AROUND COLLISION AXIS
            // --------------------------------------------------------

            let radial = cell.position - center

            let circulation =
                SIMD3<Float>(
                    -radial.y,
                     radial.x,
                     0
                ) * Float(conversion * 0.05)

            if circulation.x.isFinite &&
               circulation.y.isFinite &&
               circulation.z.isFinite {

                flow += circulation
            }

            // --------------------------------------------------------
            // BORLAGRINO DAMPING
            // --------------------------------------------------------

            let damping =
                max(
                    0.0,
                    min(
                        1.0,
                        QRTLConstants.borlagrinoDamping
                    )
                )

            flow *= Float(1.0 - damping)

            // --------------------------------------------------------
            // NUMERICAL SAFETY
            //
            // This is a dimensionless flow limit, NOT a physical
            // lattice velocity limit.
            // --------------------------------------------------------

            let flowMagnitude = simd_length(flow)

            if !flowMagnitude.isFinite {
                flow = SIMD3<Float>(0, 0, 0)

            } else if flowMagnitude > 2.0 {
                flow = simd_normalize(flow) * 2.0
            }

            nextFlow[i] = flow

            // --------------------------------------------------------
            // EMERGENT CHARGE
            //
            // Charge is derived from Borlagrino circulation.
            // It does not create physical energy.
            // --------------------------------------------------------

            var curlZ: Float = 0.0

            for ni in cell.neighbors {

                guard cells.indices.contains(ni) else {
                    continue
                }

                let neighborFlow =
                    cells[ni].borlagrinoFlow

                let positionDelta =
                    cells[ni].position - cell.position

                curlZ +=
                    neighborFlow.y * positionDelta.x
                    -
                    neighborFlow.x * positionDelta.y
            }

            let q =
                Double(curlZ) *
                QRTLConstants.chargeFromCirculation

            if q.isFinite {
                nextCharge[i] =
                    cell.charge * 0.9 +
                    q * 0.1
            } else {
                nextCharge[i] = cell.charge
            }
        }

        // ------------------------------------------------------------
        // SYNCHRONOUS COMMIT
        // ------------------------------------------------------------

        for i in cells.indices {

            cells[i].borlagrinoFlow = nextFlow[i]
            cells[i].charge = nextCharge[i]
        }

        // ------------------------------------------------------------
        // GLOBAL BORLAGRINO METRICS
        // ------------------------------------------------------------

        let n = Double(max(cells.count, 1))

        averageBorlagrinoMagnitude =
            cells.reduce(0.0) {
                let magnitude =
                    Double(simd_length($1.borlagrinoFlow))

                return $0 + (
                    magnitude.isFinite
                    ? magnitude
                    : 0.0
                )
            } / n

        netEmergentCharge =
            cells.reduce(0.0) {
                let charge = $1.charge

                return $0 + (
                    charge.isFinite
                    ? charge
                    : 0.0
                )
            }

        let absSum =
            cells.reduce(0.0) {
                let charge = $1.charge

                return $0 + (
                    charge.isFinite
                    ? abs(charge)
                    : 0.0
                )
            }

        chargeAsymmetry =
            absSum > 1.0e-12
            ? abs(netEmergentCharge) / absSum
            : 0.0
    }

