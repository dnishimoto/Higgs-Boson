        // ============================================================
        // 5. RESET COLLISION DYNAMICS
        // ============================================================

        collisionElapsedTime = 0.0

        energyShellDissipationTriggered = false

        // The shell has the energy, but the lattice has not
        // received that energy yet.
        latticeExcited = false

