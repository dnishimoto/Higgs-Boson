    private func evaluateHelium2Candidate() {

        helium2CandidateDetected = false
        helium2StableBoundState = false
        helium2DissolutionDetected = false

        helium2PeakShellEnergyGeV = 0.0
        helium2MinimumProtonSeparation = .greatestFiniteMagnitude
        helium2PersistenceSamples = 0
        helium2InitialShellEnergyGeV = 0.0

        guard cells.count >= 2 else {
            return
        }

        // --------------------------------------------------------
        // Treat the two most energetic localized regions as the
        // two proton-associated regions.
        // --------------------------------------------------------

        let sortedCells = cells.sorted {
            $0.localEnergy > $1.localEnergy
        }

        guard
            let protonA = sortedCells.first
        else {
            return
        }

        var protonB: QRTLCell?

        for candidate in sortedCells.dropFirst() {

            let dx =
                Double(candidate.position.x) -
                Double(protonA.position.x)

            let dy =
                Double(candidate.position.y) -
                Double(protonA.position.y)

            let dz =
                Double(candidate.position.z) -
                Double(protonA.position.z)

            let separation = sqrt(
                dx * dx +
                dy * dy +
                dz * dz
            )

            if separation > 0.0 {
                protonB = candidate
                break
            }
        }

        guard let protonB else {
            return
        }

        // --------------------------------------------------------
        // Proton separation
        // --------------------------------------------------------

        let dx =
            Double(protonB.position.x) -
            Double(protonA.position.x)

        let dy =
            Double(protonB.position.y) -
            Double(protonA.position.y)

        let dz =
            Double(protonB.position.z) -
            Double(protonA.position.z)

        let separation = sqrt(
            dx * dx +
            dy * dy +
            dz * dz
        )

        helium2MinimumProtonSeparation = separation

        // --------------------------------------------------------
        // Localized shell energy
        // --------------------------------------------------------

        let shellEnergyJ =
            protonA.localEnergy +
            protonB.localEnergy

        let shellEnergyGeV =
            shellEnergyJ /
            QRTLConstants.joulesPerGeV

        helium2PeakShellEnergyGeV =
            max(
                helium2PeakShellEnergyGeV,
                shellEnergyGeV
            )

        if helium2InitialShellEnergyGeV == 0.0 {
            helium2InitialShellEnergyGeV = shellEnergyGeV
        }

        // --------------------------------------------------------
        // Bound-like condition
        // --------------------------------------------------------

        let localized =
            shellEnergyGeV >=
            QRTLConstants.helium2MinimumShellEnergyGeV

        let closeEnough =
            separation <=
            QRTLConstants.helium2MaximumSeparation

        let resonancePresent =
            naturalFrequency > 0.0 &&
            resonantModeEnergyGeV > 0.0

        if localized &&
           closeEnough &&
           resonancePresent {

            helium2PersistenceSamples += 1
        } else {
            helium2PersistenceSamples = 0
        }

        // --------------------------------------------------------
        // Candidate requires temporary persistence.
        // --------------------------------------------------------

        if helium2PersistenceSamples >=
            QRTLConstants.helium2MinimumPersistenceSamples {

            helium2CandidateDetected = true
        }

        // --------------------------------------------------------
        // A stable He-2 state is deliberately NOT expected.
        //
        // If the localized shell later loses at least the
        // specified fraction of its initial energy, classify
        // the candidate as dissolved.
        // --------------------------------------------------------

        let dissolutionThreshold =
            helium2InitialShellEnergyGeV *
            QRTLConstants.helium2DissolutionEnergyFraction

        if helium2CandidateDetected &&
           shellEnergyGeV < dissolutionThreshold {

            helium2DissolutionDetected = true
            helium2StableBoundState = false
        }

        // --------------------------------------------------------
        // Debug
        // --------------------------------------------------------

        print("""
        ========================================================
        HELIUM-2 CANDIDATE TEST
        ========================================================

        Proton A cell:
            \(protonA.index)

        Proton B cell:
            \(protonB.index)

        Proton separation:
            \(separation)

        Maximum allowed separation:
            \(QRTLConstants.helium2MaximumSeparation)

        Shell energy:
            \(shellEnergyGeV) GeV

        Peak shell energy:
            \(helium2PeakShellEnergyGeV) GeV

        Resonant mode energy:
            \(resonantModeEnergyGeV) GeV

        Resonance frequency:
            \(naturalFrequency) Hz

        Persistence samples:
            \(helium2PersistenceSamples)

        Candidate detected:
            \(helium2CandidateDetected)

        Stable bound state:
            \(helium2StableBoundState)

        Dissolution detected:
            \(helium2DissolutionDetected)

        ========================================================
        """)
    }
  
   

    // ============================================================
    // IDENTIFY RESONANT MODE AND CALCULATE ITS ENERGY
    // ============================================================

    @discardableResult

    private func identifyResonantMode(
        naturalFrequency: Double
    ) -> Double {

        // ------------------------------------------------------------
        // RESET
        // ------------------------------------------------------------

        resonantModeAmplitude = 0.0
        resonantModeEnergy = 0.0
        resonantModeEnergyJ = 0.0
        resonantModeEnergyGeV = 0.0
        resonantModeEnergyTeV = 0.0

        guard naturalFrequency.isFinite,
              naturalFrequency > 0.0 else {
            return 0.0
        }

        guard collectiveSignal.count >= 8 else {
            return 0.0
        }

        let dt = QRTLConstants.timeStep

        guard dt.isFinite,
              dt > 0.0 else {
            return 0.0
        }

        let sampleCount = collectiveSignal.count

        // ------------------------------------------------------------
        // AUTHORITATIVE NATURAL ANGULAR FREQUENCY
        // ------------------------------------------------------------

        let naturalAngularFrequency =
            2.0 * Double.pi * naturalFrequency

        guard naturalAngularFrequency.isFinite,
              naturalAngularFrequency > 0.0 else {
            return 0.0
        }

        // ------------------------------------------------------------
        // REMOVE DC COMPONENT
        // ------------------------------------------------------------

        let mean =
            collectiveSignal.reduce(0.0, +) /
            Double(sampleCount)

        // ------------------------------------------------------------
        // FOURIER PROJECTION
        //
        // This is the ONLY Fourier resonance extraction path.
        // ------------------------------------------------------------

        var real = 0.0
        var imaginary = 0.0

        for sample in 0..<sampleCount {

            let signal =
                collectiveSignal[sample] - mean

            let time =
                Double(sample) * dt

            let angle =
                naturalAngularFrequency * time

            real +=
                signal * cos(angle)

            imaginary +=
                signal * sin(angle)
        }

        // ------------------------------------------------------------
        // RESONANT DISPLACEMENT AMPLITUDE
        // ------------------------------------------------------------

        let amplitude =
            (2.0 / Double(sampleCount)) *
            sqrt(
                real * real +
                imaginary * imaginary
            )

        guard amplitude.isFinite,
              amplitude > 0.0 else {
            return 0.0
        }

        resonantModeAmplitude = amplitude

        // ------------------------------------------------------------
        // PHYSICAL MODE PARAMETERS
        // ------------------------------------------------------------

        let stiffness =
            max(
                QRTLConstants.effectiveStiffnessNPerM,
                Double.leastNonzeroMagnitude
            )

        let mass =
            max(
                QRTLConstants.effectiveMassKg,
                Double.leastNonzeroMagnitude
            )

        // ------------------------------------------------------------
        // POTENTIAL ENERGY OF RESONANT MODE
        // ------------------------------------------------------------

        let potentialEnergy =
            0.5 *
            stiffness *
            amplitude *
            amplitude

        guard potentialEnergy.isFinite,
              potentialEnergy >= 0.0 else {
            return 0.0
        }

        // ------------------------------------------------------------
        // VELOCITY AMPLITUDE
        //
        // For harmonic motion:
        //
        //     V = omega * A
        //
        // ------------------------------------------------------------

        let velocityAmplitude =
            naturalAngularFrequency * amplitude

        guard velocityAmplitude.isFinite else {
            return 0.0
        }

        // ------------------------------------------------------------
        // KINETIC ENERGY OF RESONANT MODE
        // ------------------------------------------------------------

        let kineticEnergy =
            0.5 *
            mass *
            velocityAmplitude *
            velocityAmplitude

        guard kineticEnergy.isFinite,
              kineticEnergy >= 0.0 else {
            return 0.0
        }

        // ------------------------------------------------------------
        // TOTAL MECHANICAL RESONANT-MODE ENERGY
        // ------------------------------------------------------------

        let calculatedEnergy =
            potentialEnergy +
            kineticEnergy

        guard calculatedEnergy.isFinite,
              calculatedEnergy >= 0.0 else {
            return 0.0
        }

        // ------------------------------------------------------------
        // ACTUAL AVAILABLE LATTICE ENERGY
        //
        // This is the authoritative mechanical energy currently
        // stored in the simulated lattice.
        // ------------------------------------------------------------

        let latticeEnergyJ =
            totalMechanicalLatticeEnergy()

        guard latticeEnergyJ.isFinite,
              latticeEnergyJ >= 0.0 else {
            return 0.0
        }

        // ------------------------------------------------------------
        // HARD ENERGY VALIDATION
        //
        // The resonant mode cannot contain more energy than the
        // lattice actually contains.
        // ------------------------------------------------------------

        guard calculatedEnergy.isFinite,
              calculatedEnergy >= 0.0,
              calculatedEnergy <= latticeEnergyJ else {

            print("""
            ============================================================
            ⚠️ INVALID RESONANT-MODE ENERGY
            ============================================================

            Calculated mode energy:
                \(calculatedEnergy) J

            Actual lattice energy:
                \(latticeEnergyJ) J

            Excess:
                \(calculatedEnergy - latticeEnergyJ) J

            ============================================================
            """)

            return 0.0
        }

        // ------------------------------------------------------------
        // NEVER ALLOW MODE ENERGY TO EXCEED EITHER:
        //
        // 1. Actual lattice energy
        // 2. Collision energy
        // ------------------------------------------------------------

        let availableCollisionEnergy =
            max(
                collisionKineticEnergyJ,
                0.0
            )

        let boundedEnergy =
            min(
                calculatedEnergy,
                latticeEnergyJ,
                availableCollisionEnergy
            )

        // ------------------------------------------------------------
        // STORE AUTHORITATIVE RESONANT ENERGY
        // ------------------------------------------------------------

        resonantModeEnergyJ =
            max(
                boundedEnergy,
                0.0
            )

        resonantModeEnergyGeV =
            resonantModeEnergyJ /
            QRTLConstants.joulesPerGeV

        resonantModeEnergyTeV =
            resonantModeEnergyGeV /
            1_000.0

        resonantModeEnergy =
            resonantModeEnergyJ

        // ------------------------------------------------------------
        // DEBUG
        // ------------------------------------------------------------

        print("""
        ============================================================
        RESONANT MODE ANALYSIS
        ============================================================

        Samples:
            \(sampleCount)

        Sample interval:
            \(dt) s

        Natural frequency:
            \(naturalFrequency) Hz

        Natural angular frequency:
            \(naturalAngularFrequency) rad/s

        Fourier real:
            \(real)

        Fourier imaginary:
            \(imaginary)

        Resonant displacement amplitude:
            \(resonantModeAmplitude) m

        Resonant velocity amplitude:
            \(velocityAmplitude) m/s

        Potential mode energy:
            \(potentialEnergy) J

        Kinetic mode energy:
            \(kineticEnergy) J

        Calculated mechanical mode energy:
            \(calculatedEnergy) J

        Actual lattice mechanical energy:
            \(latticeEnergyJ) J

        Available collision energy:
            \(availableCollisionEnergy) J

        Resonant mode energy:
            \(resonantModeEnergyJ) J

        Resonant mode energy:
            \(resonantModeEnergyGeV) GeV

        Resonant mode energy:
            \(resonantModeEnergyTeV) TeV

        ============================================================
        """)

        return resonantModeEnergyJ
    }
    private func updateShellDissipationTrigger() {

        guard collisionOccurred else {
            return
        }

        guard !energyShellDissipationTriggered else {
            return
        }

        let elapsedSinceCollision =
            simulationTime - collisionOccurredTime

        guard elapsedSinceCollision >= shellDissipationDelay else {
            return
        }

        // ============================================================
        // 10^-22 SECOND TRANSITION
        // ============================================================

        energyShellDissipationTriggered = true

        // The collision energy is now released into the
        // QRTL lattice dynamics.
        latticeExcited = true

        print("""
        ============================================================
        QRTL SHELL DISSIPATION TRIGGER
        ============================================================
        Time since collision:
            \(elapsedSinceCollision) s

        Target delay:
            \(shellDissipationDelay) s

        collisionKineticEnergyJ:
            \(collisionKineticEnergyJ) J

        latticeExcited:
            \(latticeExcited)

        ============================================================
        """)
    }
 
    private func analyzeNaturalFrequency(
        sampleInterval: Double
    ) -> Double {

        guard sampleInterval > 0.0 else {
            return 0.0
        }

        let count =
            collectiveSignal.count

        guard count >= 32 else {
            return 0.0
        }

        let sampleRate =
            1.0 / sampleInterval

        var strongestFrequency = 0.0
        var strongestPower = 0.0

        let minimumFrequency =
            sampleRate / Double(count)

        let maximumFrequency =
            sampleRate / 2.0

        guard maximumFrequency > minimumFrequency else {
            return 0.0
        }

        for bin in 1...(count / 2) {

            let frequency =
                Double(bin) *
                sampleRate /
                Double(count)

            var real = 0.0
            var imaginary = 0.0

            for sampleIndex in 0..<count {

                let angle =
                    2.0 *
                    Double.pi *
                    Double(bin) *
                    Double(sampleIndex) /
                    Double(count)

                let sample =
                    collectiveSignal[sampleIndex]

                real +=
                    sample *
                    cos(angle)

                imaginary -=
                    sample *
                    sin(angle)
            }

            let power =
                real * real +
                imaginary * imaginary

            if power > strongestPower {

                strongestPower =
                    power

                strongestFrequency =
                    frequency
            }
        }

        return strongestFrequency
    }
    private func recordCollectiveSignal() {

        guard collisionOccurred, !cells.isEmpty else {
            return
        }

        let axis = normalizedCollisionDirection()

        var weightedDisplacement = 0.0
        var weightedVelocity = 0.0
        var totalEnergy = 0.0

        // ------------------------------------------------------------
        // Build an energy-weighted collective collision-axis signal.
        //
        // This function does NOT:
        //   • calculate natural frequency
        //   • calculate resonant energy
        //   • calculate wavelength
        //   • modify lattice energy
        //
        // It only records the physical collective motion that will
        // later be analyzed by identifyResonantMode().
        // ------------------------------------------------------------

        for cell in cells {

            let energy = max(
                Double(cell.localEnergy),
                0.0
            )

            guard energy > 1e-30 else {
                continue
            }

            let displacementProjection =
                Double(
                    simd_dot(
                        cell.displacement,
                        axis
                    )
                )

            let velocityProjection =
                Double(
                    simd_dot(
                        cell.velocity,
                        axis
                    )
                )

            guard displacementProjection.isFinite,
                  velocityProjection.isFinite else {
                continue
            }

            weightedDisplacement +=
                energy * displacementProjection

            weightedVelocity +=
                energy * velocityProjection

            totalEnergy += energy
        }

        guard totalEnergy > 1e-30 else {
            return
        }

        let collectiveDisplacement =
            weightedDisplacement / totalEnergy

        let collectiveVelocity =
            weightedVelocity / totalEnergy

        guard collectiveDisplacement.isFinite,
              collectiveVelocity.isFinite else {
            return
        }

        // ------------------------------------------------------------
        // Record the displacement as the collective oscillator signal.
        //
        // Do not add v * dt here.  identifyResonantMode() performs the
        // Fourier projection, so the recorded signal should represent
        // one physical observable consistently.
        // ------------------------------------------------------------

        collectiveSignal.append(
            collectiveDisplacement
        )

        // Keep the existing spectral sample counter if the UI uses it.
        spectralSampleCount =
            collectiveSignal.count

        spectralNyquistHz =
            0.5 / QRTLConstants.timeStep

        // ------------------------------------------------------------
        // Diagnostic output only.
        // No energy is created, removed, or reassigned here.
        // ------------------------------------------------------------

        if collectiveSignal.count <= 3 ||
           collectiveSignal.count %
           256 == 0 {

            print("""
            --------------------------------------------------------
            COLLECTIVE LATTICE SIGNAL
            --------------------------------------------------------
            Samples:
                \(collectiveSignal.count)
            Total lattice energy:
                \(totalEnergy) J
            Collective displacement:
                \(collectiveDisplacement)
            Collective velocity:
                \(collectiveVelocity)
            --------------------------------------------------------
            """)
        }
    }
    private func evaluateHiggsLikeMode() -> Bool {

        let initialEnergy =
            collisionKineticEnergyJ

        guard initialEnergy > 0.0 else {
            return false
        }

        let energyConserved =
            checkEnergyConservation(
                initialEnergy:
                    initialEnergy
            )

        let stableShell =
            evaluateStableEnergyShell()

        let frequencyValid =
            naturalFrequencyHz > 0.0

        let resonancePersistent =
            resonancePersistenceTime >=
            QRTLConstants.minimumResonanceDuration

        let coherent =
            collectiveCoherence >=
            QRTLConstants.minimumCoherence

        let energyMatch =
            isWithinHiggsEnergyWindow(
                resonantEnergy:
                    resonantModeEnergyJ
            )

        let candidate =
            energyConserved &&
            stableShell &&
            frequencyValid &&
            resonancePersistent &&
            coherent &&
            energyMatch

        print("""
        
        HIGGS-LIKE MODE EVALUATION
        
        Energy conserved:
            \(energyConserved)
        
        Stable shell:
            \(stableShell)
        
        Natural frequency:
            \(naturalFrequencyHz) Hz
        
        Resonance persistent:
            \(resonancePersistent)
        
        Coherence:
            \(collectiveCoherence)
        
        Energy match:
            \(energyMatch)
        
        Candidate mode:
            \(candidate)
        
        """)

        return candidate
    }
    private func isWithinHiggsEnergyWindow(
        resonantEnergy: Double
    ) -> Bool {

        let referenceEnergy =
            QRTLConstants.higgsReferenceEnergyJ

        guard referenceEnergy > 0.0,
              resonantEnergy > 0.0 else {
            return false
        }

        let relativeDifference =
            abs(
                resonantEnergy -
                referenceEnergy
            ) /
            referenceEnergy

        return relativeDifference <=
            QRTLConstants.higgsEnergyTolerance
    }
    private func evaluateStableEnergyShell() -> Bool {

        let currentEnergy =
            totalMechanicalLatticeEnergy()

        guard currentEnergy.isFinite,
              currentEnergy > 0.0 else {
            return false
        }

        if previousLatticeEnergy <= 0.0 {

            previousLatticeEnergy =
                currentEnergy

            return false
        }

        let energyChange =
            abs(
                currentEnergy -
                previousLatticeEnergy
            )

        let relativeChange =
            energyChange /
            max(
                currentEnergy,
                1.0e-30
            )

        previousLatticeEnergy =
            currentEnergy

        let tolerance =
            QRTLConstants.stableEnergyTolerance

        return relativeChange <
            tolerance
    }
    private func updateResonancePersistence(
        naturalFrequency: Double,
        dt: Double
    ) {

        guard naturalFrequency > 0.0 else {
            resonancePersistenceTime = 0.0
            return
        }

        resonancePersistenceTime +=
            max(
                0.0,
                dt
            )
    }
    private func checkEnergyConservation(
        initialEnergy: Double
    ) -> Bool {

        guard initialEnergy > 0.0 else {
            return false
        }

        let ejectedEnergy =
            calculateEjectedParticleEnergy()

        let currentLatticeEnergy =
            totalMechanicalLatticeEnergy()

        let accountedEnergy =
            ejectedEnergy +
            currentLatticeEnergy

        guard accountedEnergy.isFinite else {
            return false
        }

        let difference =
            abs(
                initialEnergy -
                accountedEnergy
            )

        let relativeError =
            difference /
            max(
                abs(initialEnergy),
                1.0e-30
            )

        let tolerance = 0.05

        print("""
        
        ENERGY CONSERVATION
        
        Initial energy:
            \(initialEnergy) J
        
        Ejected energy:
            \(ejectedEnergy) J
        
        Lattice energy:
            \(currentLatticeEnergy) J
        
        Accounted energy:
            \(accountedEnergy) J
        
        Relative error:
            \(relativeError)
        
        """)
        
        return relativeError <= tolerance
    }
    private func calculateStableShellEnergy() -> Double {

        guard !cells.isEmpty else {
            return 0.0
        }

        var shellEnergy = 0.0

        for cell in cells {

            let displacementMagnitude =
                Double(
                    length(cell.displacement)
                )

            let velocityMagnitude =
                Double(
                    length(cell.velocity)
                )

            let twistMagnitude =
                abs(
                    Double(cell.twist)
                )

            let phaseMagnitude =
                abs(
                    Double(cell.phase)
                )

            let displacementEnergy =
                0.5 *
                QRTLConstants.effectiveStiffnessNPerM *
                displacementMagnitude *
                displacementMagnitude

            let kineticEnergy =
                0.5 *
                QRTLConstants.effectiveMassKg *
                velocityMagnitude *
                velocityMagnitude

            let twistEnergy =
                0.5 *
                QRTLConstants.twistStiffness *
                twistMagnitude *
                twistMagnitude

            let phaseEnergy =
                0.5 *
                QRTLConstants.phaseStiffness *
                phaseMagnitude *
                phaseMagnitude

            shellEnergy +=
                displacementEnergy +
                kineticEnergy +
                twistEnergy +
                phaseEnergy
        }

        stableShellEnergyJ =
            max(
                0.0,
                shellEnergy
            )

        return stableShellEnergyJ
    }
    private func calculateEjectedParticleEnergy() -> Double {

        guard !ejectedUpQuarks.isEmpty else {
            return 0.0
        }

        let energy =
            ejectedUpQuarks.reduce(0.0) {
                partialResult,
                particle in

                guard particle.active else {
                    return partialResult
                }

                return partialResult +
                    particle.energyJ
            }

        return energy.isFinite
            ? energy
            : 0.0
    }
    private func updateEjectedUpQuarks(dt: Double) {

        guard dt > 0.0 else {
            return
        }

        guard !ejectedUpQuarks.isEmpty else {
            return
        }

        for index in ejectedUpQuarks.indices {

            guard ejectedUpQuarks[index].active else {
                continue
            }

            let velocity =
                ejectedUpQuarks[index].velocity

            ejectedUpQuarks[index].position +=
                velocity * Float(dt)
        }
    }
    private func createEjectedUpQuarks(
        collisionEnergyJ: Double,
        collisionCenter: SIMD3<Float>
    ) {

        guard collisionEnergyJ > 0.0 else {
            return
        }

        let outgoingEnergyFraction = 0.50

        let totalEjectedEnergy =
            collisionEnergyJ *
            outgoingEnergyFraction

        let energyPerParticle =
            totalEjectedEnergy / 2.0

        let upQuarkMassKg =
            QRTLConstants.upQuarkMassKg

        guard upQuarkMassKg > 0.0 else {
            return
        }

        // Relativistic energy-momentum relation:
        //
        // E² = (pc)² + (mc²)²

        let c =
            QRTLConstants.speedOfLight

        let restEnergy =
            upQuarkMassKg * c * c

        guard energyPerParticle > restEnergy else {
            return
        }

        let momentumMagnitude =
            sqrt(
                max(
                    0.0,
                    energyPerParticle *
                    energyPerParticle -
                    restEnergy *
                    restEnergy
                )
            ) / c

        let totalEnergy =
            energyPerParticle

        let gamma =
            totalEnergy / restEnergy

        let beta =
            sqrt(
                max(
                    0.0,
                    1.0 -
                    1.0 / (gamma * gamma)
                )
            )

        let speed =
            beta * c

        let momentum =
            momentumMagnitude

        let directionA =
            SIMD3<Float>(
                1.0,
                0.0,
                0.0
            )

        let directionB =
            SIMD3<Float>(
                -1.0,
                0.0,
                0.0
            )

        let velocityA =
            directionA *
            Float(speed)

        let velocityB =
            directionB *
            Float(speed)

        let momentumA =
            directionA *
            Float(momentum)
        
        let momentumB =
            directionB *
            Float(momentum)

        let offset: Float = 0.5

        ejectedUpQuarks = [

            EjectedUpQuark(
                position:
                    collisionCenter +
                    SIMD3<Float>(
                        offset,
                        0.0,
                        0.0
                    ),

                velocity:
                    velocityA,

                momentum:
                    momentumA,

                energyJ:
                    energyPerParticle,

                active:
                    true
            ),

            EjectedUpQuark(
                position:
                    collisionCenter +
                    SIMD3<Float>(
                        -offset,
                        0.0,
                        0.0
                    ),

                velocity:
                    velocityB,

                momentum:
                    momentumB,

                energyJ:
                    energyPerParticle,

                active:
                    true
            )
        ]

        ejectedEnergyJ =
            totalEjectedEnergy

        print("""
        
        EJECTED UP QUARKS
        
        Number:
            \(ejectedUpQuarks.count)
        
        Energy per particle:
            \(energyPerParticle) J
        
        Total ejected energy:
            \(ejectedEnergyJ) J
        
        Speed:
            \(speed) m/s
        
        Momentum per particle:
            \(momentum) kg·m/s
        
        """)
    }
