        Deposition error:
            \(depositionErrorJ) J
        
        Relative error:
            \(depositionRelativeError)
        
        Affected collision core:
            \(collisionCoreIndex as Any)
        
        Lattice excited:
            \(latticeExcited)
        
        ============================================================
        """)

        // ============================================================
        // MARK: - 11. FINAL COLLISION INITIALIZATION STATE
        // ============================================================

        print("""
        
        ============================================================
        COLLISION INITIALIZATION COMPLETE
        ============================================================
        
        Collision core energy:
            \(collisionCoreEnergyJ) J
        
